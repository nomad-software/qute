package rt

import (
	"reflect"
	"runtime"
)

// UserDefined reports whether method name on v is written by the user rather
// than promoted from an embedded generated wrapper. Without this check a
// promoted public virtual (SizeHint, which every Base type inherits from the
// wrapper it embeds) would dispatch to itself forever.
//
// A promoted method is followed to the type that declares it, as Go's
// selector rule does (the shallowest embedding wins), so an override declared
// on a user type that another user type embeds counts too:
//
//	type Canvas struct{ qtwidgets.QWidgetBase }
//	func (c *Canvas) PaintEvent(e *qtgui.QPaintEvent) { ... }
//	type Fancy struct{ Canvas } // PaintEvent is still an override
func UserDefined(v any, name string) bool {
	t := reflect.TypeOf(v)
	if t == nil {
		return false
	}
	level := []reflect.Type{t}
	seen := map[reflect.Type]bool{}
	for len(level) > 0 {
		var next []reflect.Type
		for _, tt := range level {
			if tt.Kind() == reflect.Pointer {
				tt = tt.Elem()
			}
			if seen[tt] {
				continue
			}
			seen[tt] = true
			if tt.Kind() == reflect.Interface {
				if _, ok := tt.MethodByName(name); ok {
					return true // an embedded interface: whatever fills it is the user's
				}
				continue
			}
			if declares(tt, name) {
				return !generatedWrapper(tt)
			}
			if tt.Kind() != reflect.Struct {
				continue
			}
			for i := 0; i < tt.NumField(); i++ {
				if f := tt.Field(i); f.Anonymous && hasMethod(f.Type, name) {
					next = append(next, f.Type)
				}
			}
		}
		level = next
	}
	return false
}

// hasMethod reports whether a value of type t, or a pointer to one, has the
// method.
func hasMethod(t reflect.Type, name string) bool {
	if _, ok := t.MethodByName(name); ok {
		return true
	}
	if t.Kind() != reflect.Pointer && t.Kind() != reflect.Interface {
		_, ok := reflect.PointerTo(t).MethodByName(name)
		return ok
	}
	return false
}

// declares reports whether the named type t declares the method itself, on a
// value or a pointer receiver. A method it only gets by promotion is a
// compiler-generated wrapper, which reports "<autogenerated>" as its file.
func declares(t reflect.Type, name string) bool {
	for _, tt := range []reflect.Type{reflect.PointerTo(t), t} {
		m, ok := tt.MethodByName(name)
		if !ok {
			continue
		}
		pc := m.Func.Pointer()
		f := runtime.FuncForPC(pc)
		if f == nil {
			continue
		}
		if file, _ := f.FileLine(pc); file != "<autogenerated>" {
			return true
		}
	}
	return false
}

var refType = reflect.TypeFor[Ref]()

// generatedWrapper reports whether t is a generated type: a wrapper struct,
// whose primary-base chain starts with a Ref (the layout every wrapper has),
// or a Base type, which holds only a pointer to its wrapper (and declares the
// class's protected methods, never an override).
func generatedWrapper(t reflect.Type) bool {
	if t.Kind() == reflect.Struct && t.NumField() == 1 {
		if f := t.Field(0); f.Anonymous && f.Type.Kind() == reflect.Pointer {
			t = f.Type.Elem()
		}
	}
	for t.Kind() == reflect.Struct && t.NumField() > 0 {
		f := t.Field(0)
		if f.Type == refType {
			return true
		}
		if !f.Anonymous {
			return false
		}
		t = f.Type
	}
	return false
}
