func (g *Gen) initStructs() {
	core := g.byName["QtCore"]
	gui := g.byName["QtGui"]
	i := func(goName, cName string) structField { return structField{goName, cName, "int", "C.int"} }
	f := func(goName, cName string) structField { return structField{goName, cName, "float64", "C.double"} }
	u := func(goName, cName string) structField { return structField{goName, cName, "uint8", "C.uchar"} }
	defs := []*structDef{
		{name: "QPoint", module: core, cType: "qute_point", fields: []structField{i("X", "x"), i("Y", "y")}},
		{name: "QPointF", module: core, cType: "qute_pointf", fields: []structField{f("X", "x"), f("Y", "y")}},
		{name: "QSize", module: core, cType: "qute_size", fields: []structField{i("Width", "w"), i("Height", "h")}},
		{name: "QSizeF", module: core, cType: "qute_sizef", fields: []structField{f("Width", "w"), f("Height", "h")}},
		{name: "QRect", module: core, cType: "qute_rect", fields: []structField{i("X", "x"), i("Y", "y"), i("Width", "w"), i("Height", "h")}},
		{name: "QRectF", module: core, cType: "qute_rectf", fields: []structField{f("X", "x"), f("Y", "y"), f("Width", "w"), f("Height", "h")}},
		{name: "QMargins", module: core, cType: "qute_margins", fields: []structField{i("Left", "l"), i("Top", "t"), i("Right", "r"), i("Bottom", "b")}},
		{name: "QColor", module: gui, cType: "qute_color", fields: []structField{u("R", "r"), u("G", "g"), u("B", "b"), u("A", "a")}},
	}
	for _, d := range defs {
		if d.module != nil {
			g.structs[d.name] = d
		}
	}
}

func (g *Gen) structList() []*structDef {
	order := []string{"QPoint", "QPointF", "QSize", "QSizeF", "QRect", "QRectF", "QMargins", "QColor"}
	var out []*structDef
	for _, n := range order {
		if s := g.structs[n]; s != nil {
			out = append(out, s)
		}
	}
	return out
}

