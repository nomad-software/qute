package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

type Report struct {
	warnings []string
	noTest   []string
	blind    []string
}

// unobservable records a Parented result that Qt itself created from a
// non-QObject class: nothing tells Go when its owner frees it.
func (r *Report) unobservable(c *Class, m *Method) {
	r.blind = append(r.blind, fmt.Sprintf("- `%s`", m.Sig))
}

func (r *Report) untested(c *Class, m *Method, why string) {
	r.noTest = append(r.noTest, fmt.Sprintf("- `%s`: %s", m.Sig, why))
}

func (r *Report) warn(format string, a ...any) {
	r.warnings = append(r.warnings, fmt.Sprintf(format, a...))
}

// writeReport lists every method that passes or returns a pointer with only a
// default ownership rule, every numbered overload name, and every skipped
// method, so coverage gaps are visible in review.
func (g *Gen) writeReport(path string) error {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	p("<!-- Code generated by qutegen. DO NOT EDIT. -->")
	p("# Binding coverage\n")
	p("Generated by `go generate ./qtcore` (cmd/qutegen). It records what is bound,")
	p("what is left out on purpose and why, and anything that still needs a person:")
	p("a default ownership rule, a numbered overload name, a type the generator")
	p("cannot map yet, or a rule without a generated test. Fix an open item with an")
	p("overlay entry in `spec/overlays/<module>.yaml` (an ownership rule,")
	p("`reviewed: true`, a `name`, `skip`, or a `test:` snippet), then regenerate.")
	p("A constructor argument named `parent` is treated as reviewed (`transfer-this`).\n")
	p("{{SUMMARY}}")

	type row struct{ cls, text string }
	var rules, numbered, skipped []row
	total := 0
	for _, m := range g.modules {
		for _, c := range m.Classes {
			all := append(append(append([]*Method{}, c.Ctors...), c.Methods...), c.Statics...)
			for _, mm := range all {
				total++
				var defaults []string
				for _, prm := range mm.Params {
					if mm.IR.Kind == "ctor" && prm.Rule == "transfer-this" && prm.Name == "parent" {
						continue // the constructor parent heuristic is the one default treated as reviewed
					}
					if (prm.T.k == kObj || prm.T.k == kList && prm.T.elem.k == kObj) && !prm.Ruled {
						defaults = append(defaults, fmt.Sprintf("`%s`: %s", prm.GoName, prm.Rule))
					}
				}
				if mm.RetRule != "" && !mm.RetRuled {
					defaults = append(defaults, "return: "+mm.RetRule)
				}
				// emitting a signal never changes ownership
				rev := c.Opts.Reviewed || mm.Emit || (mm.Overlay != nil && mm.Overlay.Reviewed)
				if len(defaults) > 0 && !rev {
					rules = append(rules, row{c.Name, fmt.Sprintf("- `%s` → %s", mm.Sig, strings.Join(defaults, ", "))})
				}
				if mm.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- `%s` → `%s`", mm.Sig, mm.GoName)})
				}
			}
			for _, sg := range c.Signals {
				if sg.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- signal `%s` → `%s`", sg.Sig, sg.GoName)})
				}
			}
			for _, v := range c.Virtuals {
				if v.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- virtual `%s` → `%s`", v.Sig, v.GoName)})
				}
			}
			seen := map[string]bool{}
			for _, s := range c.Skipped {
				k := s.Sig + s.Why
				if seen[k] {
					continue
				}
				seen[k] = true
				skipped = append(skipped, row{c.Name, fmt.Sprintf("- `%s`: %s", s.Sig, s.Why)})
			}
		}
	}
	section := func(title string, rows []row) {
		p("## %s (%d)\n", title, len(rows))
		sort.SliceStable(rows, func(i, j int) bool { return rows[i].cls < rows[j].cls })
		last := ""
		for _, r := range rows {
			if r.cls != last {
				p("\n### %s\n", r.cls)
				last = r.cls
			}
			p("%s", r.text)
		}
		p("")
	}
	section("Default ownership rules", rules)
	section("Numbered overload names", numbered)
	// split deliberate skips from ones waiting for type support
	var onPurpose, missing []row
	byType := map[string]int{}
	for _, r := range skipped {
		if i := strings.Index(r.text, "unsupported type \""); i >= 0 {
			t := r.text[i+len("unsupported type \""):]
			t = t[:strings.Index(t, "\"")]
			base, _, ptr, ref, _ := parseCpp(t)
			if ptr && !ref && prims[base].goT != "" {
				base += " * (out-parameter or buffer)"
			} else if ref && prims[base].goT != "" || base == "QString" || base == "QRect" || base == "QTransform" {
				base += " & (out-parameter)"
			}
			byType[base]++
			missing = append(missing, r)
		} else {
			onPurpose = append(onPurpose, r)
		}
	}
	p("## Skipped: missing type support (%d)\n", len(missing))
	p("These bind once the generator learns the type. Counts by type:\n")
	type tc struct {
		t string
		n int
	}
	var tcs []tc
	for t, n := range byType {
		tcs = append(tcs, tc{t, n})
	}
	sort.Slice(tcs, func(i, j int) bool { return tcs[i].n > tcs[j].n || tcs[i].n == tcs[j].n && tcs[i].t < tcs[j].t })
	p("| Type | Methods |\n| --- | --- |")
	for _, x := range tcs {
		p("| `%s` | %d |", x.t, x.n)
	}
	p("")
	section("Skipped: missing type support, by class", missing)
	section("Skipped on purpose", onPurpose)
	if len(g.report.noTest) > 0 {
		p("## Ownership rules without a generated test (%d)\n", len(g.report.noTest))
		p("Add a `test:` snippet to the overlay entry to cover these.\n")
		for _, w := range g.report.noTest {
			p("%s", w)
		}
		p("")
	}
	if len(g.report.blind) > 0 {
		p("## Results whose death qute cannot see (%d)\n", len(g.report.blind))
		p("Qt creates these items itself, and they are not QObjects, so no death notice")
		p("reaches Go. The handle is Parented and correct while the owner lives; after")
		p("the owner is deleted, do not use it.\n")
		for _, w := range g.report.blind {
			p("%s", w)
		}
		p("")
	}
	if len(g.report.warnings) > 0 {
		p("## Generator warnings (%d)\n", len(g.report.warnings))
		for _, w := range g.report.warnings {
			p("- %s", w)
		}
	}
	open := len(rules) + len(numbered) + len(missing) + len(g.report.noTest) + len(g.report.blind)
	var sum strings.Builder
	fmt.Fprintf(&sum, "## Summary\n\n| | Count |\n| --- | --- |\n")
	fmt.Fprintf(&sum, "| Bound constructors, methods and functions | %d |\n", total)
	fmt.Fprintf(&sum, "| Skipped on purpose (with reasons below) | %d |\n", len(onPurpose))
	fmt.Fprintf(&sum, "| Default ownership rules to review | %d |\n", len(rules))
	fmt.Fprintf(&sum, "| Numbered overload names | %d |\n", len(numbered))
	fmt.Fprintf(&sum, "| Waiting for type support | %d |\n", len(missing))
	fmt.Fprintf(&sum, "| Ownership rules without a generated test | %d |\n", len(g.report.noTest))
	fmt.Fprintf(&sum, "| Results whose death qute cannot see | %d |\n\n", len(g.report.blind))
	if open == 0 {
		fmt.Fprintf(&sum, "Nothing is open.\n\n")
	} else {
		fmt.Fprintf(&sum, "%d item(s) open; see their sections below.\n\n", open)
	}
	return writeFile(path, []byte(strings.Replace(b.String(), "{{SUMMARY}}\n", sum.String(), 1)))
}

var _ = os.Stdout
