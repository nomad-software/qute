package main

import (
	"fmt"
	"sort"
	"strings"
)

type Report struct {
	warnings []string
	noTest   []string
}

func (r *Report) untested(m *Method, why string) {
	r.noTest = append(r.noTest, fmt.Sprintf("- `%s`: %s", m.Sig, why))
}

func (r *Report) warn(format string, a ...any) {
	r.warnings = append(r.warnings, fmt.Sprintf(format, a...))
}

// writeReport lists every method that passes or returns a pointer with only a
// default ownership rule, every numbered overload name, and every skipped
// method, so coverage gaps are visible in review.
func (g *Gen) writeReport(path string) error {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	p("<!-- Code generated by qutegen. DO NOT EDIT. -->")
	p("# Binding coverage\n")
	p("Generated by `go generate ./qtcore` (cmd/qutegen). It records what is bound,")
	p("what is left out on purpose and why, and anything that still needs a person:")
	p("a default ownership rule, a numbered overload name, a type the generator")
	p("cannot map yet, or a rule without a generated test. Fix an open item with an")
	p("overlay entry in `spec/overlays/<module>.yaml` (an ownership rule,")
	p("`reviewed: true`, a `name`, `skip`, or a `test:` snippet), then regenerate.")
	p("A constructor argument named `parent` is treated as reviewed (`transfer-this`).")
	p("An out-parameter guessed from its type (`int *`, `QString &`) stays open until")
	p("an `out` or `in-out` rule confirms it: the type alone cannot say whether Qt")
	p("wants an array or also reads the value.\n")
	p("{{SUMMARY}}")

	type row struct{ cls, text string }
	var rules, numbered, skipped, notIR []row
	droppedBy := map[string]int{}
	total, fulls, tied := 0, 0, 0
	var blind []string // results whose death qute cannot see
	var noSub []row    // object classes Go cannot subclass, with why
	subclassable := 0
	var noVirt []row             // virtuals Go cannot override, with why
	var noFull, noFullOpen []row // methods without a Full form, with why
	inherited := map[string]bool{}
	for _, m := range g.modules {
		for _, c := range m.Classes {
			all := append(append(append([]*Method{}, c.Ctors...), c.Methods...), c.Statics...)
			for _, mm := range all {
				total++
				if mm.FullOf != nil {
					// the same rules as its short form, reported there, except
					// for the defaulted arguments only the Full form takes
					fulls++
					if d := defaultRules(&Method{IR: mm.IR, Params: mm.Params[len(mm.FullOf.Params):]}); len(d) > 0 && !reviewed(c, mm) {
						rules = append(rules, row{c.Name, fmt.Sprintf("- `%s` (Full form) → %s", mm.Sig, strings.Join(d, ", "))})
					}
					continue
				}
				switch plainResult(mm) {
				case "tied":
					tied++
				case "blind":
					blind = append(blind, fmt.Sprintf("- `%s`", mm.Sig))
				}
				defaults := defaultRules(mm)
				// emitting a signal never changes ownership; an inferred
				// out-parameter needs its own `out`/`in-out` rule
				rev := reviewed(c, mm)
				for _, prm := range mm.Params {
					if (prm.Out || prm.InOut) && !prm.Ruled {
						rev = false
					}
				}
				if len(defaults) > 0 && !rev {
					rules = append(rules, row{c.Name, fmt.Sprintf("- `%s` → %s", mm.Sig, strings.Join(defaults, ", "))})
				}
				if mm.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- `%s` → `%s`", mm.Sig, mm.GoName)})
				}
			}
			// Protected methods and virtuals are inherited by every subclass's
			// Base; they are reviewed once, on the class that declares them.
			for _, mm := range c.Protected {
				if key := mm.Owner.Name + "|" + mm.Sig; !inherited[key] {
					inherited[key] = true
					if mm.Numbered {
						numbered = append(numbered, row{mm.Owner.Name, fmt.Sprintf("- protected `%s` → `%s`", mm.Sig, mm.GoName)})
					}
					if d := defaultRules(mm); len(d) > 0 && !(mm.Overlay != nil && mm.Overlay.Reviewed) && !mm.Owner.Opts.Reviewed {
						rules = append(rules, row{mm.Owner.Name, fmt.Sprintf("- protected `%s` → %s", mm.Sig, strings.Join(d, ", "))})
					}
				}
			}
			for _, v := range c.Virtuals {
				if key := "virtual|" + v.Owner.Name + "|" + v.Sig; !inherited[key] {
					inherited[key] = true
					if d := virtualDefaults(v); len(d) > 0 {
						rules = append(rules, row{v.Owner.Name, fmt.Sprintf("- virtual `%s` → %s", v.Sig, strings.Join(d, ", "))})
					}
				}
			}
			seenFull := map[string]bool{}
			for _, n := range c.NoFull {
				if seenFull[n.Sig] {
					continue
				}
				seenFull[n.Sig] = true
				r := row{c.Name, fmt.Sprintf("- `%s`: %s", n.Sig, n.Why)}
				if strings.HasPrefix(n.Why, "on purpose") {
					noFull = append(noFull, r)
				} else {
					noFullOpen = append(noFullOpen, r)
				}
			}
			for _, n := range c.NoVirtuals {
				noVirt = append(noVirt, row{c.Name, fmt.Sprintf("- `%s`: %s", n.Sig, n.Why)})
			}
			if c.Opts.Subclass {
				subclassable++
			} else if c.Opts.NoSubclass != "" {
				noSub = append(noSub, row{c.Name, "- " + c.Opts.NoSubclass})
			}
			for _, sg := range c.Signals {
				if sg.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- signal `%s` → `%s`", sg.Sig, sg.GoName)})
				}
			}
			for _, v := range c.Virtuals {
				if v.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- virtual `%s` → `%s`", v.Sig, v.GoName)})
				}
			}
			byKind := map[string][]string{}
			for _, d := range c.IR.Dropped {
				byKind[d.Kind] = append(byKind[d.Kind], "`"+d.Name+"`")
				droppedBy[d.Kind]++
			}
			for _, k := range []string{"conversion", "operator", "template"} {
				if len(byKind[k]) > 0 {
					notIR = append(notIR, row{c.Name, fmt.Sprintf("- %ss: %s", k, strings.Join(byKind[k], ", "))})
				}
			}
			seen := map[string]bool{}
			for _, s := range c.Skipped {
				k := s.Sig + s.Why
				if seen[k] {
					continue
				}
				seen[k] = true
				skipped = append(skipped, row{c.Name, fmt.Sprintf("- `%s`: %s", s.Sig, s.Why)})
			}
		}
	}
	section := func(title string, rows []row) {
		p("## %s (%d)\n", title, len(rows))
		sort.SliceStable(rows, func(i, j int) bool { return rows[i].cls < rows[j].cls })
		last := ""
		for _, r := range rows {
			if r.cls != last {
				p("\n### %s\n", r.cls)
				last = r.cls
			}
			p("%s", r.text)
		}
		p("")
	}
	section("Default ownership rules", rules)
	section("Numbered overload names", numbered)
	// split deliberate skips from ones waiting for type support
	var onPurpose, missing []row
	byType := map[string]int{}
	for _, r := range skipped {
		if i := strings.Index(r.text, "unsupported type \""); i >= 0 {
			t := r.text[i+len("unsupported type \""):]
			t = t[:strings.Index(t, "\"")]
			base, _, ptr, ref, _ := parseCpp(t)
			if ptr && !ref && prims[base].goT != "" {
				base += " * (out-parameter or buffer)"
			} else if ref && prims[base].goT != "" || base == "QString" || base == "QRect" || base == "QTransform" {
				base += " & (out-parameter)"
			}
			byType[base]++
			missing = append(missing, r)
		} else {
			onPurpose = append(onPurpose, r)
		}
	}
	p("## Skipped: missing type support (%d)\n", len(missing))
	p("These bind once the generator learns the type. Counts by type:\n")
	type tc struct {
		t string
		n int
	}
	var tcs []tc
	for t, n := range byType {
		tcs = append(tcs, tc{t, n})
	}
	sort.Slice(tcs, func(i, j int) bool { return tcs[i].n > tcs[j].n || tcs[i].n == tcs[j].n && tcs[i].t < tcs[j].t })
	p("| Type | Methods |\n| --- | --- |")
	for _, x := range tcs {
		p("| `%s` | %d |", x.t, x.n)
	}
	p("")
	section("Skipped: missing type support, by class", missing)
	section("Skipped on purpose", onPurpose)
	section("Virtuals Go cannot override", noVirt)
	p("## Full forms not built\n")
	p("These methods are bound without their defaulted arguments, but their Full")
	p("form, which takes every argument, cannot be built. Open ones need an `out` or")
	p("`in-out` rule on a defaulted pointer (`bool *ok`), or type support; the others")
	p("are left out on purpose (`no-full` in the overlay, or a type-wide reason).\n")
	section("Full forms not built: open", noFullOpen)
	section("Full forms not built on purpose", noFull)
	p("## Classes Go cannot subclass (%d)\n", len(noSub))
	p("Every other bound class with virtuals can be subclassed from Go: embed its")
	p("Base and construct with New<Class>With. These cannot:\n")
	sort.SliceStable(noSub, func(i, j int) bool { return noSub[i].cls < noSub[j].cls })
	for _, r := range noSub {
		p("- `%s`: %s", r.cls, strings.TrimPrefix(r.text, "- "))
	}
	p("")
	p("## Not in the IR: operators, conversions and member templates (%d)\n", droppedBy["operator"]+droppedBy["conversion"]+droppedBy["template"])
	p("tools/irgen leaves these out before the IR is written, so the generator never")
	p("sees them and they are not counted as bound or skipped above. Go has no")
	p("operator overloading: comparisons and arithmetic are done on the Go structs or")
	p("through named methods. Conversions to QVariant are covered by")
	p("`qtgui.NewQVariantOf`, and `QVariant::value<T>()` by `QVariant.Value` and")
	p("`qtgui.VariantValue`. Counts: %d operators, %d conversion operators, %d member templates.\n",
		droppedBy["operator"], droppedBy["conversion"], droppedBy["template"])
	sort.SliceStable(notIR, func(i, j int) bool { return notIR[i].cls < notIR[j].cls })
	last := ""
	for _, r := range notIR {
		if r.cls != last {
			p("\n### %s\n", r.cls)
			last = r.cls
		}
		p("%s", r.text)
	}
	p("")
	if len(g.report.noTest) > 0 {
		p("## Ownership rules without a generated test (%d)\n", len(g.report.noTest))
		p("Add a `test:` snippet to the overlay entry to cover these.\n")
		for _, w := range g.report.noTest {
			p("%s", w)
		}
		p("")
	}
	if len(blind) > 0 {
		p("## Results whose death qute cannot see (%d)\n", len(blind))
		p("These functions return an object Qt made that is neither a QObject nor a")
		p("notifying subclass, and they have no receiver the result could depend on,")
		p("so nothing tells Go when it is freed. Do not keep the result.\n")
		for _, w := range blind {
			p("%s", w)
		}
		p("")
	}
	if len(g.report.warnings) > 0 {
		p("## Generator warnings (%d)\n", len(g.report.warnings))
		for _, w := range g.report.warnings {
			p("- %s", w)
		}
	}
	open := len(rules) + len(numbered) + len(missing) + len(g.report.noTest) + len(blind) + len(noFullOpen)
	var sum strings.Builder
	fmt.Fprintf(&sum, "## Summary\n\n| | Count |\n| --- | --- |\n")
	fmt.Fprintf(&sum, "| Bound constructors, methods and functions | %d |\n", total)
	fmt.Fprintf(&sum, "| of which Full forms (every argument, defaults included) | %d |\n", fulls)
	fmt.Fprintf(&sum, "| Plain-object results that depend on their receiver | %d |\n", tied)
	fmt.Fprintf(&sum, "| Skipped on purpose (with reasons below) | %d |\n", len(onPurpose))
	fmt.Fprintf(&sum, "| Classes Go can subclass | %d |\n", subclassable)
	fmt.Fprintf(&sum, "| Classes Go cannot subclass (with reasons below) | %d |\n", len(noSub))
	fmt.Fprintf(&sum, "| Virtuals Go cannot override (with reasons below) | %d |\n", len(noVirt))
	fmt.Fprintf(&sum, "| Operators, conversions and member templates not in the IR | %d |\n",
		droppedBy["operator"]+droppedBy["conversion"]+droppedBy["template"])
	fmt.Fprintf(&sum, "| Default ownership rules to review | %d |\n", len(rules))
	fmt.Fprintf(&sum, "| Numbered overload names | %d |\n", len(numbered))
	fmt.Fprintf(&sum, "| Waiting for type support | %d |\n", len(missing))
	fmt.Fprintf(&sum, "| Full forms not built (open) | %d |\n", len(noFullOpen))
	fmt.Fprintf(&sum, "| Full forms not built on purpose | %d |\n", len(noFull))
	fmt.Fprintf(&sum, "| Ownership rules without a generated test | %d |\n", len(g.report.noTest))
	fmt.Fprintf(&sum, "| Results whose death qute cannot see | %d |\n\n", len(blind))
	if open == 0 {
		fmt.Fprintf(&sum, "Nothing is open.\n\n")
	} else {
		fmt.Fprintf(&sum, "%d item(s) open; see their sections below.\n\n", open)
	}
	return writeFile(path, []byte(strings.Replace(b.String(), "{{SUMMARY}}\n", sum.String(), 1)))
}

// plainResult classifies a method whose result is a plain object Qt made
// (not a QObject, value copy or object built by the binding), which qute
// cannot watch: "tied" when it depends on the receiver (WrapClassFrom: Use
// panics once the receiver is gone), "blind" for a function with no
// receiver (unless an overlay marks it reviewed), "" otherwise. A plain base of QObject classes (QPaintDevice)
// still counts: the pointer may be a plain object too.
// reviewed reports whether the default rules of mm were checked: by the
// overlay, or because emitting a signal never changes ownership.
func reviewed(c *Class, mm *Method) bool {
	return c.Opts.Reviewed || mm.Emit || (mm.Overlay != nil && mm.Overlay.Reviewed)
}

// defaultRules lists the ownership rules of mm that no overlay states.
func defaultRules(mm *Method) []string {
	var defaults []string
	for _, prm := range mm.Params {
		if mm.IR.Kind == "ctor" && prm.Rule == "transfer-this" && prm.Name == "parent" {
			continue // the constructor parent heuristic is the one default treated as reviewed
		}
		if (prm.T.k == kObj || prm.T.k == kList && prm.T.elem.k == kObj) && !prm.Ruled {
			defaults = append(defaults, fmt.Sprintf("`%s`: %s", prm.GoName, prm.Rule))
		}
		if (prm.Out || prm.InOut) && !prm.Ruled {
			// guessed from the type: Qt may want an array, or read the value too
			defaults = append(defaults, fmt.Sprintf("`%s`: %s (inferred)", prm.GoName, prm.Rule))
		}
	}
	if mm.RetRule != "" && !mm.RetRuled {
		defaults = append(defaults, "return: "+mm.RetRule)
	}
	return defaults
}

// virtualDefaults lists what a Go override of v returns to Qt on a default
// rule: an object result says nothing about who owns it until an overlay on
// the declaring class gives a return rule (or marks it reviewed).
func virtualDefaults(v *Method) []string {
	if v.Ret.k != kObj || v.RetRuled || v.Overlay != nil && v.Overlay.Reviewed {
		return nil
	}
	return []string{"result kept by Go (no return rule)"}
}

func plainResult(mm *Method) string {
	if mm.Ret == nil || mm.IR == nil || mm.IR.Kind == "ctor" || mm.Overlay != nil && mm.Overlay.Created {
		return ""
	}
	t := mm.Ret
	if t.k == kList {
		t = t.elem
	}
	if t == nil || t.k != kObj || t.cls.Kind != KindPlain || mm.RetRule == "transfer-to-go" {
		return ""
	}
	if mm.IR.Static {
		if mm.Overlay != nil && mm.Overlay.Reviewed {
			return "" // a person checked how long it lives (doc says)
		}
		return "blind"
	}
	return "tied"
}
