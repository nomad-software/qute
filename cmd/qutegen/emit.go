func (g *Gen) includes(m *Module) []string {
	set := map[string]bool{}
	var walk func(x *Module)
	walk = func(x *Module) {
		for _, c := range x.Classes {
			set[strings.Split(c.Cpp, "::")[0]] = true
		}
		for _, d := range x.Deps {
			walk(d)
		}
	}
	walk(m)
	var out []string
	for n := range set {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

func (g *Gen) emitCpp(m *Module, b *buf) {
	b.p("%s", strings.TrimSuffix(genHeader, "\n"))
	b.p("#include \"%s_gen.h\"\n", m.Pkg)
	for _, inc := range g.includes(m) {
		b.p("#include <%s>", inc)
	}
	b.p("\n#include <QtCore/QCoreApplication>\n#include <QtCore/QThread>\n#include <cstring>\n#include <memory>\n")
	b.p("extern \"C\" {")
	b.p("void qute_%s_signal(uintptr_t id, void *args);", m.Pkg)
	b.p("void qute_%s_release(uintptr_t id);", m.Pkg)
	b.p("bool qute_%s_virtual(uintptr_t id, int idx, void *args, void *ret);", m.Pkg)
	b.p("void qute_%s_wrong_thread(void);", m.Pkg)
	b.p("void qute_%s_dead(void *key);", m.Pkg)
	b.p("void qute_%s_call(uintptr_t id, void *args, void *ret);", m.Pkg)
	b.p("}\n")
	b.p("static inline void qute_call(uintptr_t id, void *args, void *ret) { qute_%s_call(id, args, ret); }\n", m.Pkg)
	b.p("// Every Qt call must come from the GUI thread; the Go side panics otherwise.")
	b.p("// It is checked here, where it costs a thread-local read, so release builds")
	b.p("// catch it too (qute_debug builds also name the method).")
	b.p("static inline void qute_gui_only() {")
	b.p("\tQCoreApplication *app = QCoreApplication::instance();")
	b.p("\tif (app && QThread::currentThread() != app->thread()) {\n\t\tqute_%s_wrong_thread();\n\t}\n}\n", m.Pkg)
	b.p("namespace {")
	b.p("// GoSlot owns a Go closure id; Qt destroys the slot object on disconnect")
	b.p("// or when the sender dies, which releases the closure.")
	b.p("struct GoSlot {\n\tuintptr_t id;\n\texplicit GoSlot(uintptr_t i) : id(i) {}\n\t~GoSlot() { qute_%s_release(id); }\n};", m.Pkg)
	b.p("} // namespace\n")
	for _, c := range m.Classes {
		if c.Shim {
			g.emitShimClass(c, b)
		}
	}
	b.p("extern \"C\" {\n")
	// layout check: the runtime relies on every primary base sitting at offset 0
	b.p("const char *qute_%s_check_layout(void) {", m.Pkg)
	for _, c := range m.Classes {
		if c.Base == nil || c.Opts.EnumsOnly {
			continue
		}
		b.p("\t{ %s *d = reinterpret_cast<%s *>(uintptr_t(0x10000)); %s *bp = d; if (reinterpret_cast<uintptr_t>(bp) != 0x10000) return %q; }", c.Cpp, c.Cpp, c.Base.Cpp, c.Name)
	}
	b.p("\treturn nullptr;\n}\n")
	for _, c := range m.Classes {
		b.p("// ---- %s", c.Name)
		for _, f := range g.classCFuncs(c) {
			b.p("%s {\n\tqute_gui_only();\n\t%s\n}", f.decl, f.body)
		}
		b.p("")
	}
	b.p("} // extern \"C\"")
}

func (g *Gen) emitShimClass(c *Class, b *buf) {
	cls := c.Name
	n := (len(c.Virtuals) + 63) / 64
	if n == 0 {
		n = 1
	}
	b.p("class qute_%s : public %s {\npublic:", cls, c.Cpp)
	b.p("\tusing %s::%s;", c.Cpp, lastName(c.Cpp))
	b.p("\tuintptr_t qute_id = 0;\n\tuint64_t qute_mask[%d] = {};", n)
	b.p("\tbool qute_has(int i) const { return qute_id && ((qute_mask[i / 64] >> (i %% 64)) & 1); }")
	if c.Kind != KindObject {
		b.p("\t~qute_%s() override { qute_%s_dead(static_cast<void *>(static_cast<%s *>(this))); }", cls, c.Module.Pkg, c.Cpp)
	}
	protNames := map[string]bool{}
	for _, v := range c.Protected {
		if !protNames[v.IR.Name] {
			protNames[v.IR.Name] = true
			b.p("\tusing %s::%s;", v.Owner.Cpp, v.IR.Name)
		}
	}
	for _, v := range c.Virtuals {
		var decl, names []string
		for _, p := range v.Params {
			decl = append(decl, fmt.Sprintf("%s %s", v.IR.Params[indexOf(v, p)].Type.Canonical, p.CName))
			names = append(names, p.CName)
		}
		cst := ""
		if v.IR.Const {
			cst = " const"
		}
		rt := v.IR.Return.Canonical
		b.p("\t%s %s(%s)%s override {", rt, v.IR.Name, strings.Join(decl, ", "), cst)
		b.p("\t\tif (qute_has(%d)) {", v.VIndex)
		var refs []string
		for i, p := range v.Params {
			switch {
			case p.View && p.T.inplace:
				b.p("\t\t\tvoid * c%d = static_cast<void *>(&%s);", i, p.CName)
			case p.View:
				b.p("\t\t\tvoid * c%d = static_cast<void *>(%s);", i, p.CName)
			default:
				b.p("\t\t\t%s c%d = %s;", cType(p.T), i, g.cppRet(p.T, p.CName))
			}
			refs = append(refs, fmt.Sprintf("&c%d", i))
		}
		args := "nullptr"
		if len(refs) > 0 {
			b.p("\t\t\tvoid *args[] = {%s};", strings.Join(refs, ", "))
			args = "args"
		}
		// false: the Go value is gone (its tree was collected and is about to
		// be deleted), so the C++ implementation runs instead
		if v.Ret.k == kVoid {
			b.p("\t\t\tif (qute_%s_virtual(qute_id, %d, %s, nullptr)) {\n\t\t\t\treturn;\n\t\t\t}", c.Module.Pkg, v.VIndex, args)
		} else {
			if v.Ret.k == kValue || v.Ret.k == kObj {
				b.p("\t\t\t%s r = nullptr;", cType(v.Ret))
			} else {
				b.p("\t\t\t%s r{};", cType(v.Ret))
			}
			b.p("\t\t\tif (qute_%s_virtual(qute_id, %d, %s, &r)) {\n\t\t\t\treturn %s;\n\t\t\t}", c.Module.Pkg, v.VIndex, args, g.cppVirtRet(v.Ret, "r"))
		}
		b.p("\t\t}")
		if v.IR.Pure {
			if v.Ret.k == kVoid {
				b.p("\t\treturn;")
			} else {
				b.p("\t\treturn %s();", strings.TrimSuffix(strings.TrimPrefix(v.IR.Return.Canonical, "const "), " &"))
			}
		} else {
			call := fmt.Sprintf("%s::%s(%s)", v.Owner.Cpp, v.IR.Name, strings.Join(names, ", "))
			if v.Ret.k == kVoid {
				b.p("\t\t%s;", call)
			} else {
				b.p("\t\treturn %s;", call)
			}
		}
		b.p("\t}")
		if !v.IR.Pure {
			b.p("\t%s qute_super_%d(%s)%s { return %s::%s(%s); }", rt, v.VIndex, strings.Join(decl, ", "), cst, v.Owner.Cpp, v.IR.Name, strings.Join(names, ", "))
		}
	}
	b.p("};\n")
}

func indexOf(m *Method, p *Param) int {
	for i, q := range m.Params {
		if q == p {
			return i
		}
	}
	return -1
}

