func cDecl(ret string, name string, params []string) string {
	if len(params) == 0 {
		params = []string{"void"}
	}
	return fmt.Sprintf("%s %s(%s)", ret, name, strings.Join(params, ", "))
}

func methodCParams(mm *Method, self bool) []string {
	var ps []string
	if self {
		ps = append(ps, "void *self")
	}
	for _, p := range mm.Params {
		switch {
		case p.Out:
			ps = append(ps, outCType(p.T)+" *"+p.CName+"_out")
		case p.InOut:
			ps = append(ps, cParams(p.T, p.CName)...)
			ps = append(ps, outCType(p.T)+" *"+p.CName+"_out")
		default:
			ps = append(ps, cParams(p.T, p.CName)...)
		}
	}
	for i, t := range mm.PairRet {
		ps = append(ps, fmt.Sprintf("%s *r%d_out", outCType(t), i))
	}
	return ps
}

func outCType(c *conv) string {
	if c.k == kValue {
		return "void *"
	}
	return cType(c)
}

// cppCall builds the statements and arguments of a Qt call from the C
// parameters: locals for out-parameters and pairs before, write-backs after.
func (g *Gen) cppCall(params []*Param) (pre, args, post []string) {
	for i, p := range params {
		t := fmt.Sprintf("t%d", i)
		switch {
		case p.Out || p.InOut:
			if p.InOut {
				pre = append(pre, fmt.Sprintf("%s %s = %s;", p.CppT, t, g.cppArg(p.T, p.CName)))
			} else {
				pre = append(pre, fmt.Sprintf("%s %s{};", p.CppT, t))
			}
			if p.ByPtr {
				args = append(args, "&"+t)
			} else {
				args = append(args, t)
			}
			post = append(post, fmt.Sprintf("*%s_out = %s;", p.CName, g.cppRet(p.T, t)))
		case p.Pair == "array":
			pre = append(pre, fmt.Sprintf("auto %s = %s;", t, g.cppArg(p.T, p.CName)))
			args = append(args, fmt.Sprintf("%s.constData()", t), fmt.Sprintf("%s.size()", t))
		case p.Pair == "bytes":
			args = append(args, fmt.Sprintf("reinterpret_cast<const %s *>(%s)", p.T.base, p.CName), p.CName+"_len")
		case p.Pair == "buffer":
			args = append(args, fmt.Sprintf("const_cast<char *>(%s)", p.CName), p.CName+"_len")
		default:
			args = append(args, g.cppArg(p.T, p.CName))
		}
	}
	return
}

// cppBody wraps a call expression with the out-parameter handling.
func (g *Gen) cppBody(ret *conv, call string, pre, post []string) string {
	var b []string
	b = append(b, pre...)
	if ret == nil || ret.k == kVoid || ret.k == kSelf {
		b = append(b, call+";")
		b = append(b, post...)
		return strings.Join(b, "\n\t")
	}
	if len(post) == 0 {
		b = append(b, "return "+g.cppRet(ret, call)+";")
		return strings.Join(b, "\n\t")
	}
	b = append(b, "auto &&r = "+call+";")
	b = append(b, post...)
	b = append(b, "return "+g.cppRet(ret, "r")+";")
	return strings.Join(b, "\n\t")
}

func retCType(mm *Method) string {
	if mm.Ret == nil || mm.Ret.k == kVoid || mm.Ret.k == kSelf {
		return "void"
	}
	return cType(mm.Ret)
}

type cFunc struct {
	decl string
	body string
}

func (g *Gen) classCFuncs(c *Class) []cFunc {
	var out []cFunc
	if c.Opts.EnumsOnly {
		return nil
	}
	add := func(decl, body string) { out = append(out, cFunc{decl, body}) }
	cls, cpp := c.Name, c.Cpp
	self := fmt.Sprintf("static_cast<%s *>(self)", cpp)
	ctorClass := cpp
	if c.Shim && c.Kind != KindObject {
		ctorClass = "qute_" + cls // notify-dtor shims always construct the shim
	}
	for _, mm := range c.Ctors {
		pre, args, _ := g.cppCall(mm.Params)
		add(cDecl("void *", mm.CName, methodCParams(mm, false)),
			strings.Join(append(pre, fmt.Sprintf("return static_cast<%s *>(new %s(%s));", cpp, ctorClass, strings.Join(args, ", "))), "\n\t"))
	}
	if c.Opts.Subclass && c.Shim {
		if pc := primaryCtor(c); pc != nil {
			var args []string
			for _, p := range pc.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			add(cDecl("void *", "qute_"+cls+"_new_shim", methodCParams(pc, false)),
				fmt.Sprintf("return static_cast<%s *>(new qute_%s(%s));", cpp, cls, strings.Join(args, ", ")))
		}
		add(cDecl("void", "qute_"+cls+"_shim_init", []string{"void *self", "uintptr_t id", "const uint64_t *mask"}),
			fmt.Sprintf("auto s = static_cast<qute_%s *>(static_cast<%s *>(self)); s->qute_id = id; std::memcpy(s->qute_mask, mask, sizeof(s->qute_mask));", cls, cpp))
		for _, v := range c.Virtuals {
			if v.IR.Pure {
				continue
			}
			var args []string
			for _, p := range v.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			call := fmt.Sprintf("static_cast<qute_%s *>(static_cast<%s *>(self))->qute_super_%d(%s)", cls, cpp, v.VIndex, strings.Join(args, ", "))
			body := call + ";"
			if v.Ret.k != kVoid {
				body = "return " + g.cppRet(v.Ret, call) + ";"
			}
			add(cDecl(cType(v.Ret), v.CName, methodCParams(v, true)), body)
		}
		for _, v := range c.Protected {
			var args []string
			for _, p := range v.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			call := fmt.Sprintf("static_cast<qute_%s *>(static_cast<%s *>(self))->%s(%s)", cls, cpp, v.IR.Name, strings.Join(args, ", "))
			body := call + ";"
			if v.Ret.k != kVoid {
				body = "return " + g.cppRet(v.Ret, call) + ";"
			}
			add(cDecl(retCType(v), v.CName, methodCParams(v, true)), body)
		}
	}
	if c.Kind != KindObject && c.HasDtor && (c.IR.Dtor == nil || c.IR.Dtor.Access == "public") {
		add(cDecl("void", "qute_"+cls+"_delete", []string{"void *self"}), fmt.Sprintf("delete %s;", self))
	}
	if c.QBase {
		add(cDecl("void *", "qute_"+cls+"_qobject", []string{"void *self"}),
			fmt.Sprintf("return static_cast<void *>(dynamic_cast<QObject *>(%s));", self))
	}
	if c.Opts.Memory != nil {
		add(cDecl("int64_t", "qute_"+cls+"_memory", []string{"void *self"}),
			fmt.Sprintf("return static_cast<int64_t>(%s);", expandCpp(c.Opts.Memory.Size, fmt.Sprintf("static_cast<const %s *>(self)", cpp), nil)))
	}
	if c.QObject {
		add(cDecl("void *", "qute_"+cls+"_cast", []string{"void *obj"}),
			fmt.Sprintf("return static_cast<void *>(qobject_cast<%s *>(static_cast<QObject *>(obj)));", cpp))
	}
	for i, d := range c.Opts.DependsOn {
		if d.Cpp != "" {
			expr := expandCpp(d.Cpp, fmt.Sprintf("static_cast<const %s *>(self)", cpp), nil)
			add(cDecl("void *", fmt.Sprintf("qute_%s_dep%d", cls, i), []string{"void *self"}),
				fmt.Sprintf("return const_cast<void *>(static_cast<const void *>(%s));", expr))
		}
	}
	for _, s := range c.Secondary {
		add(cDecl("void *", fmt.Sprintf("qute_%s_as_%s", cls, s.Name), []string{"void *self"}),
			fmt.Sprintf("return static_cast<void *>(static_cast<%s *>(%s));", s.Cpp, self))
	}
	for _, mm := range append(append([]*Method{}, c.Methods...), c.Statics...) {
		pre, args, post := g.cppCall(mm.Params)
		var call string
		if mm.Field == "get" {
			add(cDecl(retCType(mm), mm.CName, methodCParams(mm, true)), "return "+g.cppRet(mm.Ret, self+"->"+mm.IR.Name)+";")
			continue
		}
		if mm.Field == "set" {
			add(cDecl("void", mm.CName, methodCParams(mm, true)), fmt.Sprintf("%s->%s = %s;", self, mm.IR.Name, args[0]))
			continue
		}
		if mm.Overlay != nil && mm.Overlay.Cpp != "" {
			call = expandCpp(mm.Overlay.Cpp, self, args)
		} else if mm.IR.Static {
			call = fmt.Sprintf("%s::%s(%s)", cpp, mm.IR.Name, strings.Join(args, ", "))
		} else {
			call = fmt.Sprintf("%s->%s(%s)", self, mm.IR.Name, strings.Join(args, ", "))
		}
		if len(mm.PairRet) == 2 {
			body := strings.Join(append(pre, "auto &&r = "+call+";",
				"*r0_out = "+g.cppRet(mm.PairRet[0], "r.first")+";",
				"*r1_out = "+g.cppRet(mm.PairRet[1], "r.second")+";"), "\n\t")
			add(cDecl("void", mm.CName, methodCParams(mm, !mm.IR.Static)), body)
			continue
		}
		add(cDecl(retCType(mm), mm.CName, methodCParams(mm, !mm.IR.Static)), g.cppBody(mm.Ret, call, pre, post))
	}
	for _, sg := range c.Signals {
		out = append(out, g.signalCFunc(c, sg))
	}
	return out
}

func primaryCtor(c *Class) *Method {
	for _, m := range c.Ctors {
		if m.GoName == "New"+c.Name {
			return m
		}
	}
	if len(c.Ctors) > 0 {
		return c.Ctors[0]
	}
	for _, m := range c.ShimCtors {
		if len(m.Params) == 1 && m.Params[0].Rule == "transfer-this" {
			return m
		}
	}
	if len(c.ShimCtors) > 0 {
		return c.ShimCtors[0]
	}
	return nil
}

func (g *Gen) signalCFunc(c *Class, sg *Method) cFunc {
	cls := c.Cpp
	// any method of the same name makes &Class::name ambiguous, not only
	// another signal: QAudioDecoder has error() and the signal error(Error)
	overloaded := 0
	for i := range c.IR.Methods {
		if c.IR.Methods[i].Name == sg.IR.Name {
			overloaded++
		}
	}
	ptr := fmt.Sprintf("&%s::%s", cls, sg.IR.Name)
	if overloaded > 1 {
		var ts []string
		for _, p := range sg.IR.Params {
			ts = append(ts, p.Type.Canonical)
		}
		ptr = fmt.Sprintf("static_cast<void (%s::*)(%s)>(%s)", cls, strings.Join(ts, ", "), ptr)
	}
	var lparams, conv, refs []string
	for i, p := range sg.Params {
		lparams = append(lparams, fmt.Sprintf("%s %s", p.T.cpp, p.CName))
		conv = append(conv, fmt.Sprintf("%s c%d = %s;", cType(p.T), i, g.cppRet(p.T, p.CName)))
		refs = append(refs, fmt.Sprintf("&c%d", i))
	}
	args := "nullptr"
	argDecl := ""
	if len(refs) > 0 {
		argDecl = fmt.Sprintf(" void *args[] = {%s};", strings.Join(refs, ", "))
		args = "args"
	}
	body := fmt.Sprintf("auto s = std::make_shared<GoSlot>(id);\n\tauto obj = static_cast<%s *>(self);\n"+
		"\treturn new QMetaObject::Connection(QObject::connect(obj, %s, obj, [s](%s) {%s%s qute_%s_signal(s->id, %s); }));",
		cls, ptr, strings.Join(lparams, ", "), " "+strings.Join(conv, " "), argDecl, c.Module.Pkg, args)
	return cFunc{decl: cDecl("void *", sg.CName, []string{"void *self", "uintptr_t id"}), body: body}
}

func (g *Gen) emitHeader(m *Module, b *buf) {
	guard := "QUTE_" + strings.ToUpper(m.Pkg) + "_GEN_H"
	b.p("%s", strings.TrimSuffix(genHeader, "\n"))
	b.p("#ifndef %s\n#define %s\n", guard, guard)
	b.p("#include \"qute_common.h\"\n")
	b.p("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
	b.p("const char *qute_%s_check_layout(void);", m.Pkg)
	for _, c := range m.Classes {
		b.p("\n// %s", c.Name)
		for _, f := range g.classCFuncs(c) {
			b.p("%s;", f.decl)
		}
	}
	b.p("\n#ifdef __cplusplus\n}\n#endif\n\n#endif")
}

