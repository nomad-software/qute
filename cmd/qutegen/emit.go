const goHelpers = `
var (
	_ = quteStr
	_ = quteBytes
	_ = quteStrList
	_ = quteStrListArg
	_ = quteCStr
	_ = quteCBytes
	_ = quteCStrList
	_ = quteFreeStrs
)

var _ = quteMap[C.int, C.int, int, int]
var _ = qutePairs[C.int, C.int, int, int, int]

// quteStr copies a malloc'd UTF-8 buffer into a Go string and frees it.
func quteStr(s C.qute_str) string {
	r := C.GoStringN(s.data, C.int(s.len))
	C.free(unsafe.Pointer(s.data))
	return r
}

func quteBytes(s C.qute_str) []byte {
	r := C.GoBytes(unsafe.Pointer(s.data), C.int(s.len))
	C.free(unsafe.Pointer(s.data))
	return r
}

func quteStrList(l C.qute_list) []string {
	ss := unsafe.Slice((*C.qute_str)(l.data), int(l.len))
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = quteStr(s)
	}
	C.free(l.data)
	return out
}

func quteList[CT any, G any](l C.qute_list, f func(CT) G) []G {
	es := unsafe.Slice((*CT)(l.data), int(l.len))
	out := make([]G, len(es))
	for i, e := range es {
		out[i] = f(e)
	}
	C.free(l.data)
	return out
}

func quteMap[CK comparable, CV any, K comparable, V any](m C.qute_map, kf func(CK) K, vf func(CV) V) map[K]V {
	ks := quteList(m.keys, kf)
	vs := quteList(m.values, vf)
	out := make(map[K]V, len(ks))
	for i, k := range ks {
		out[k] = vs[i]
	}
	return out
}

func qutePairs[CK any, CV any, K any, V any, P any](m C.qute_map, kf func(CK) K, vf func(CV) V, mk func(K, V) P) []P {
	ks := quteList(m.keys, kf)
	vs := quteList(m.values, vf)
	out := make([]P, len(ks))
	for i := range ks {
		out[i] = mk(ks[i], vs[i])
	}
	return out
}

// quteStrListArg packs strings as one buffer plus lengths: Go memory with no
// Go pointers in it, so it may be passed to C directly.
func quteStrListArg(v []string) ([]byte, []C.ptrdiff_t) {
	n := 1
	for _, s := range v {
		n += len(s)
	}
	data := make([]byte, 0, n)
	lens := make([]C.ptrdiff_t, len(v)+1)
	for i, s := range v {
		data = append(data, s...)
		lens[i] = C.ptrdiff_t(len(s))
	}
	return data[:cap(data)], lens
}

// quteCStr copies a Go string into C memory the shim frees.
func quteCStr(s string) C.qute_str {
	return C.qute_str{data: (*C.char)(C.CBytes([]byte(s))), len: C.ptrdiff_t(len(s))}
}

func quteCBytes(b []byte) C.qute_str {
	return C.qute_str{data: (*C.char)(C.CBytes(b)), len: C.ptrdiff_t(len(b))}
}

func quteCStrList(v []string) C.qute_list {
	n := len(v)
	if n == 0 {
		n = 1
	}
	p := C.malloc(C.size_t(n) * C.size_t(unsafe.Sizeof(C.qute_str{})))
	ss := unsafe.Slice((*C.qute_str)(p), len(v))
	for i, s := range v {
		ss[i] = quteCStr(s)
	}
	return C.qute_list{data: p, len: C.ptrdiff_t(len(v))}
}

func quteFreeStrs(v []C.qute_str) {
	for _, s := range v {
		C.free(unsafe.Pointer(s.data))
	}
}
`

