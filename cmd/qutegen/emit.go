func kindConst(c *Class) string {
	switch {
	case c.Kind == KindValue:
		return "rt.KindValue"
	case c.QObject:
		return "rt.KindQObject"
	case c.Shim:
		return "rt.KindNotify"
	}
	return "rt.KindPlain"
}

func (g *Gen) deleterExpr(c *Class) string {
	if c.QObject {
		return "rt.DeleteQObject"
	}
	if c.HasDtor {
		return fmt.Sprintf("func(p unsafe.Pointer) { C.qute_%s_delete(p) }", c.Name)
	}
	return "nil"
}

func (g *Gen) emitClass(c *Class) []byte {
	m := c.Module
	m.imports = map[string]bool{}
	var b buf
	cls := c.Name
	core := g.byName["QtCore"]

	// type
	kindDoc := map[ClassKind]string{
		KindObject: "It is a QObject: Go tracks its ownership and learns when Qt destroys it.",
		KindPlain:  "",
		KindValue:  "It is a Qt value class: each Go handle owns its own copy, freed by GC or Delete().",
	}[c.Kind]
	b.p("// %s wraps Qt's %s.", cls, cls)
	if kindDoc != "" {
		b.p("// %s", kindDoc)
	}
	if c.Event {
		b.p("// Event arguments are valid only inside the handler that receives them.")
	}
	b.p("//\n// Qt docs: %s", docURL(c, ""))
	if c.Base == nil {
		b.p("type %s struct{ quteRef rt.Ref }\n", cls)
	} else {
		b.p("type %s struct{ %s }\n", cls, g.qual(c.Base.Module, m, c.Base.Name))
	}
	b.p("// %sLike is implemented by *%s and every type that embeds it.", cls, cls)
	b.p("type %sLike interface{ As%s() *%s }\n", cls, cls, cls)
	b.p("// As%s returns the receiver; it lets derived types be passed as %sLike.", cls, cls)
	b.p("func (this *%s) As%s() *%s { return this }\n", cls, cls, cls)
	b.p("func init() { rt.RegisterClass(%q, %s, %s) }\n", cls, kindConst(c), g.deleterExpr(c))
	if c.QBase {
		b.p("// A %s may be a QObject (through a QObject subclass); its wrapper then", cls)
		b.p("// shares that object's handle and learns of its death.")
		b.p("func init() {\n\trt.RegisterBaseOfQObject(%q, func(p unsafe.Pointer) unsafe.Pointer { return C.qute_%s_qobject(p) })\n}\n", cls, cls)
	}
	if mem := c.Opts.Memory; mem != nil {
		if c.Kind != KindValue {
			g.report.warn("%s: memory option on a class that is not a value class", cls)
		}
		b.p("// Each %s counts the bytes it holds outside the Go heap, so GC runs as they add up.", cls)
		b.p("func init() {\n\trt.RegisterMemory(%q, func(p unsafe.Pointer) int64 { return int64(C.qute_%s_memory(p)) })\n}\n", cls, cls)
		for _, n := range mem.ChangedBy {
			found := false
			for _, mm := range c.Methods {
				found = found || mm.IR.Name == n
			}
			if !found {
				g.report.warn("%s: memory changed-by %q is not a bound method", cls, n)
			}
		}
	}
	if len(c.Opts.DependsOn) > 0 && c.QObject {
		g.report.warn("%s: depends-on on a QObject class does nothing; its death is watched directly", cls)
	}
	for i, dep := range c.Opts.DependsOn {
		if dep.Cpp != "" {
			if dc := g.classes[dep.Class]; dc == nil || dc.Opts.EnumsOnly {
				g.report.warn("%s: depends-on class %q is not bound", cls, dep.Class)
				continue
			}
			b.p("// Every %s holds the %s it belongs to (depends-on, found in C++).", cls, dep.Class)
			b.p("func init() {\n\trt.RegisterDependency(%q, func(p unsafe.Pointer) *rt.Handle {", cls)
			b.p("\t\treturn rt.WrapClass(C.qute_%s_dep%d(p), %q, rt.KeepOrBorrow)\n\t})\n}\n", cls, i, dep.Class)
			continue
		}
		// the getter may be declared on a base (QWidgetItem::widget overrides
		// QLayoutItem's); its shim takes the base pointer, which every primary
		// base shares
		var getter *Method
		for k := c; k != nil && getter == nil; k = k.Base {
			for _, mm := range k.Methods {
				if mm.IR.Name == dep.Getter && len(mm.Params) == 0 && mm.Ret != nil && mm.Ret.k == kObj && !mm.Ret.ref {
					getter = mm
				}
			}
		}
		if getter == nil {
			g.report.warn("%s: depends-on %q is not a bound getter returning an object pointer", cls, dep.Getter)
		} else {
			b.p("// Every %s holds the %s it belongs to (depends-on: %s).", cls, getter.Ret.cls.Name, dep.Getter)
			b.p("func init() {\n\trt.RegisterDependency(%q, func(p unsafe.Pointer) *rt.Handle {", cls)
			b.p("\t\treturn rt.WrapClass(C.%s(p), %q, rt.KeepOrBorrow)\n\t})\n}\n", getter.CName, getter.Ret.cls.Name)
		}
	}
	own := g.qual(core, m, "Ownership")
	b.p("// %sFromPtr wraps an existing C++ %s. This is an unsafe escape hatch: own says", cls, cls)
	b.p("// who frees the object (Borrowed keeps the state of an already wrapped object).")
	b.p("func %sFromPtr(p unsafe.Pointer, own %s) *%s {", cls, own, cls)
	b.p("\treturn rt.View[%s](rt.WrapClass(p, %q, rt.ModeFor(own)), p)\n}\n", cls, cls)
	if c.QObject {
		ol := g.qual(core, m, "QObjectLike")
		b.p("// %sCast returns o as a *%s if it is one (qobject_cast), or nil.", cls, cls)
		b.p("func %sCast(o %s) *%s {", cls, ol, cls)
		b.p("\tif o == nil {\n\t\treturn nil\n\t}")
		b.p("\tself := rt.UseArg(unsafe.Pointer(o.AsQObject()), %q)", cls+"Cast")
		b.p("\tif self == nil {\n\t\treturn nil\n\t}")
		b.p("\tp := C.qute_%s_cast(self)\n\tif p == nil {\n\t\treturn nil\n\t}", cls)
		b.p("\treturn rt.View[%s](rt.WrapClass(p, %q, rt.KeepOrBorrow), p)\n}\n", cls, cls)
	}
	if c.Base == nil {
		g.emitRootMethods(c, &b)
	}
	for _, s := range c.Secondary {
		st := g.qual(s.Module, m, s.Name)
		b.p("// As%s returns the %s part of this object, sharing its ownership state.", s.Name, s.Name)
		b.p("func (this *%s) As%s() *%s {", cls, s.Name, st)
		b.p("\tself := rt.Use(unsafe.Pointer(this), %q)", cls+".As"+s.Name)
		b.p("\tp := C.qute_%s_as_%s(self)", cls, s.Name)
		b.p("\treturn rt.View[%s](rt.RefOf(unsafe.Pointer(this)).H, p)\n}\n", st)
	}
	for _, mm := range c.Ctors {
		g.emitCtor(c, mm, &b)
	}
	for _, mm := range c.Methods {
		g.emitMethod(c, mm, &b, false)
	}
	for _, mm := range c.Statics {
		g.emitMethod(c, mm, &b, true)
	}
	for _, sg := range c.Signals {
		g.emitSignal(c, sg, &b)
	}
	if c.Opts.Subclass && c.Shim {
		g.emitSubclass(c, &b)
	}
	var out buf
	g.preamble(m, &out)
	std := []string{"unsafe"}
	if bytes.Contains(b.Bytes(), []byte("fmt.")) {
		std = append([]string{"fmt"}, std...)
	}
	if bytes.Contains(b.Bytes(), []byte("runtime.KeepAlive(")) {
		std = append(std, "runtime")
	}
	if timeRef.Match(b.Bytes()) {
		std = append(std, "time")
	}
	g.importBlock(m, &out, std)
	out.Write(b.Bytes())
	return out.Bytes()
}

func (g *Gen) emitRootMethods(c *Class, b *buf) {
	cls := c.Name
	own := g.qual(g.byName["QtCore"], c.Module, "Ownership")
	b.p("// Ptr returns the C++ pointer (unsafe escape hatch). It is nil for a nil receiver.")
	b.p("func (this *%s) Ptr() unsafe.Pointer {\n\tif this == nil {\n\t\treturn nil\n\t}\n\treturn this.quteRef.P\n}\n", cls)
	b.p("// Alive reports whether the C++ object still exists.")
	b.p("func (this *%s) Alive() bool { return this != nil && this.quteRef.H.Alive() }\n", cls)
	b.p("// Ownership reports who frees the object: Owned, Parented, Borrowed or Dead.")
	b.p("func (this *%s) Ownership() %s {\n\tif this == nil {\n\t\treturn rt.Dead\n\t}\n\treturn this.quteRef.H.State()\n}\n", cls, own)
	b.p("// Delete destroys the C++ object now. It is idempotent and works on Owned and")
	b.p("// Parented objects; on Borrowed objects it panics. Inside a signal or event")
	b.p("// handler use DeleteLater() instead.")
	b.p("func (this *%s) Delete() {\n\tif this == nil {\n\t\treturn\n\t}\n\trt.CheckThread(%q)\n\tthis.quteRef.H.Delete(%q)\n}\n", cls, cls+".Delete", cls+".Delete")
	b.p("// Keep pins the object so GC never frees it, until Unkeep.")
	b.p("func (this *%s) Keep() {\n\tif this != nil {\n\t\tthis.quteRef.H.Keep()\n\t}\n}\n", cls)
	b.p("// Unkeep releases one Keep.")
	b.p("func (this *%s) Unkeep() {\n\tif this != nil {\n\t\tthis.quteRef.H.Unkeep()\n\t}\n}\n", cls)
}

func (g *Gen) docLines(c *Class, mm *Method, b *buf, what string) {
	b.p("// %s wraps %s.", mm.GoName, what)
	b.p("//\n//\tC++: %s", mm.Sig)
	var rules []string
	for _, p := range mm.Params {
		if p.Rule == "" || p.Rule == "borrowed" && !p.Ruled || p.Out || p.InOut {
			continue
		}
		switch p.Keep {
		case "":
		case "release":
			rules = append(rules, fmt.Sprintf("%s is borrowed, and the receiver drops the reference it kept to it", p.GoName))
			continue
		default:
			who := "the receiver"
			if mm.IR.Kind == "ctor" {
				who = "the new object"
			}
			rules = append(rules, fmt.Sprintf("%s is borrowed, and %s keeps it from being garbage collected while it lives", p.GoName, who))
			continue
		}
		desc := map[string]string{
			"transfer-to-cpp": "becomes Parented: Qt frees it from now on",
			"transfer-to-go":  "becomes Owned: Go frees it from now on",
			"transfer-this":   "the receiver becomes Parented when it is non-nil, Owned when nil",
			"borrowed":        "is borrowed for the call only",
			"scoped":          "is valid only during the call",
		}[p.Rule]
		rules = append(rules, fmt.Sprintf("%s %s", p.GoName, desc))
	}
	switch mm.RetRule {
	case "transfer-to-go":
		rules = append(rules, "the result is Owned: Go frees it")
	case "parented":
		rules = append(rules, "the result is Parented: its Qt parent frees it")
	case "borrowed":
		rules = append(rules, "the result is Borrowed: Go never frees it")
	}
	if mm.Ret != nil && mm.Ret.k == kValue {
		rules = append(rules, "the result is an Owned copy")
	}
	if len(rules) > 0 {
		b.p("//\n// Ownership: %s.", strings.Join(rules, "; "))
	}
	if mm.Overlay != nil && mm.Overlay.Doc != "" {
		b.p("//\n// %s", mm.Overlay.Doc)
	}
	if mm.FullOf != nil {
		b.p("//\n// %s is %s with every argument, including those %s leaves at their C++ defaults.", mm.GoName, mm.FullOf.GoName, mm.FullOf.GoName)
	} else if mm.FullName != "" {
		b.p("//\n// Arguments with C++ defaults are left at them; %s takes every argument.", mm.FullName)
	}
	anchor := mm.IR.Name
	if mm.IR.Kind == "ctor" {
		anchor = mm.Class.Name
	}
	b.p("//\n// Qt docs: %s", docURL(mm.Owner, anchor))
}

