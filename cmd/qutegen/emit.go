func (g *Gen) emitEnums(m *Module) []byte {
	var b buf
	b.p("%s", strings.TrimSuffix(genHeader, "\n"))
	b.p("package %s\n", m.Pkg)
	for _, e := range m.Enums {
		valPrefix := ""
		if i := strings.LastIndex(e.cpp, "::"); i >= 0 {
			scope := e.cpp[:i]
			if scope != "Qt" {
				valPrefix = strings.ReplaceAll(scope, "::", "")
			}
		}
		if e.ir.Scoped {
			valPrefix += e.ir.Name
		}
		typ := e.goName
		if e.anon {
			b.p("// Constants from an unnamed enum in %s.", strings.TrimSuffix(e.cpp, "::"+e.ir.Name))
			typ = ""
		} else if e.flagsName != "" {
			b.p("// %s is the flags type for %s (QFlags<%s>).", e.flagsName, e.cpp, e.cpp)
			b.p("type %s int64\n", e.flagsName)
			b.p("// Has reports whether every bit of x is set in f.")
			b.p("func (f %s) Has(x %s) bool { return f&x == x }\n", e.flagsName, e.flagsName)
			b.p("// %s wraps the enum %s. It is the same type as %s, so values combine with |.", e.goName, e.cpp, e.flagsName)
			b.p("type %s = %s\n", e.goName, e.flagsName)
			typ = e.flagsName
		} else {
			b.p("// %s wraps the enum %s.", e.goName, e.cpp)
			b.p("type %s int64\n", e.goName)
		}
		var lines []string
		for _, v := range e.ir.Values {
			n := valPrefix + v.Name
			if !m.claim(n, "value "+e.cpp+"::"+v.Name) {
				n = valPrefix + e.ir.Name + v.Name
				if !m.claim(n, "value "+e.cpp+"::"+v.Name) {
					continue
				}
			}
			if typ == "" {
				lines = append(lines, fmt.Sprintf("\t%s = %d", n, v.Value))
			} else {
				lines = append(lines, fmt.Sprintf("\t%s %s = %d", n, typ, v.Value))
			}
		}
		if len(lines) > 0 {
			b.p("const (")
			for _, l := range lines {
				b.p("%s", l)
			}
			b.p(")\n")
		}
	}
	return b.Bytes()
}

