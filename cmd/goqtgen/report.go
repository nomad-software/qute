package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

type Report struct {
	warnings []string
	noTest   []string
}

func (r *Report) untested(c *Class, m *Method, why string) {
	r.noTest = append(r.noTest, fmt.Sprintf("- `%s`: %s", m.Sig, why))
}

func (r *Report) warn(format string, a ...any) {
	r.warnings = append(r.warnings, fmt.Sprintf(format, a...))
}

// writeReport lists every method that passes or returns a pointer with only a
// default ownership rule, every numbered overload name, and every skipped
// method, so coverage gaps are visible in review.
func (g *Gen) writeReport(path string) error {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	p("<!-- Code generated by goqtgen. DO NOT EDIT. -->")
	p("# Unreviewed bindings\n")
	p("Generated by `go generate ./...` (cmd/goqtgen). Each entry below relies on a")
	p("default rule. Fix one by adding an overlay entry in `spec/overlays/<module>.yaml`")
	p("(an ownership rule, `reviewed: true`, a `name`, or `skip`), then regenerate.")
	p("A constructor argument named `parent` is treated as reviewed (`transfer-this`).\n")

	type row struct{ cls, text string }
	var rules, numbered, skipped []row
	total, reviewed := 0, 0
	for _, m := range g.modules {
		for _, c := range m.Classes {
			all := append(append(append([]*Method{}, c.Ctors...), c.Methods...), c.Statics...)
			for _, mm := range all {
				total++
				var defaults []string
				for _, prm := range mm.Params {
					if mm.IR.Kind == "ctor" && prm.Rule == "transfer-this" && prm.Name == "parent" {
						continue // the constructor parent heuristic is the one default treated as reviewed
					}
					if (prm.T.k == kObj || prm.T.k == kList && prm.T.elem.k == kObj) && !prm.Ruled {
						defaults = append(defaults, fmt.Sprintf("`%s`: %s", prm.GoName, prm.Rule))
					}
				}
				if mm.RetRule != "" && !mm.RetRuled {
					defaults = append(defaults, "return: "+mm.RetRule)
				}
				rev := c.Opts.Reviewed || (mm.Overlay != nil && mm.Overlay.Reviewed)
				if len(defaults) > 0 && !rev {
					rules = append(rules, row{c.Name, fmt.Sprintf("- `%s` → %s", mm.Sig, strings.Join(defaults, ", "))})
				} else {
					reviewed++
				}
				if mm.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- `%s` → `%s`", mm.Sig, mm.GoName)})
				}
			}
			for _, v := range c.Virtuals {
				if v.Numbered {
					numbered = append(numbered, row{c.Name, fmt.Sprintf("- virtual `%s` → `%s`", v.Sig, v.GoName)})
				}
			}
			seen := map[string]bool{}
			for _, s := range c.Skipped {
				k := s.Sig + s.Why
				if seen[k] {
					continue
				}
				seen[k] = true
				skipped = append(skipped, row{c.Name, fmt.Sprintf("- `%s`: %s", s.Sig, s.Why)})
			}
		}
	}
	section := func(title string, rows []row) {
		p("## %s (%d)\n", title, len(rows))
		sort.SliceStable(rows, func(i, j int) bool { return rows[i].cls < rows[j].cls })
		last := ""
		for _, r := range rows {
			if r.cls != last {
				p("\n### %s\n", r.cls)
				last = r.cls
			}
			p("%s", r.text)
		}
		p("")
	}
	p("Bound: %d constructors, methods and functions; %d need no review or are reviewed.\n", total, reviewed)
	section("Default ownership rules", rules)
	section("Numbered overload names", numbered)
	section("Skipped methods", skipped)
	if len(g.report.noTest) > 0 {
		p("## Ownership rules without a generated test (%d)\n", len(g.report.noTest))
		p("Add a `test:` snippet to the overlay entry to cover these.\n")
		for _, w := range g.report.noTest {
			p("%s", w)
		}
		p("")
	}
	if len(g.report.warnings) > 0 {
		p("## Generator warnings (%d)\n", len(g.report.warnings))
		for _, w := range g.report.warnings {
			p("- %s", w)
		}
	}
	return writeFile(path, []byte(b.String()))
}

var _ = os.Stdout
