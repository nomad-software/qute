func (g *Gen) includes(m *Module) []string {
	set := map[string]bool{}
	var walk func(x *Module)
	walk = func(x *Module) {
		for _, c := range x.Classes {
			set[c.Name] = true
		}
		for _, d := range x.Deps {
			walk(d)
		}
	}
	walk(m)
	var out []string
	for n := range set {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

func (g *Gen) emitCpp(m *Module, b *buf) {
	b.p("%s", strings.TrimSuffix(genHeader, "\n"))
	b.p("#include \"%s_gen.h\"\n", m.Pkg)
	for _, inc := range g.includes(m) {
		b.p("#include <%s>", inc)
	}
	b.p("\n#include <cstring>\n#include <memory>\n")
	b.p("extern \"C\" {")
	b.p("void goqt_%s_signal(uintptr_t id, void *args);", m.Pkg)
	b.p("void goqt_%s_release(uintptr_t id);", m.Pkg)
	b.p("void goqt_%s_virtual(uintptr_t id, int idx, void *args, void *ret);", m.Pkg)
	b.p("void goqt_%s_dead(void *key);", m.Pkg)
	b.p("}\n")
	b.p("namespace {")
	b.p("// GoSlot owns a Go closure id; Qt destroys the slot object on disconnect")
	b.p("// or when the sender dies, which releases the closure.")
	b.p("struct GoSlot {\n\tuintptr_t id;\n\texplicit GoSlot(uintptr_t i) : id(i) {}\n\t~GoSlot() { goqt_%s_release(id); }\n};", m.Pkg)
	b.p("} // namespace\n")
	for _, c := range m.Classes {
		if c.Shim {
			g.emitShimClass(c, b)
		}
	}
	b.p("extern \"C\" {\n")
	// layout check: the runtime relies on every primary base sitting at offset 0
	b.p("const char *goqt_%s_check_layout(void) {", m.Pkg)
	for _, c := range m.Classes {
		if c.Base == nil {
			continue
		}
		b.p("\t{ %s *d = reinterpret_cast<%s *>(uintptr_t(0x10000)); %s *bp = d; if (reinterpret_cast<uintptr_t>(bp) != 0x10000) return %q; }", c.Name, c.Name, c.Base.Name, c.Name)
	}
	b.p("\treturn nullptr;\n}\n")
	for _, c := range m.Classes {
		b.p("// ---- %s", c.Name)
		for _, f := range g.classCFuncs(c) {
			b.p("%s {\n\t%s\n}", f.decl, f.body)
		}
		b.p("")
	}
	b.p("} // extern \"C\"")
}

func (g *Gen) emitShimClass(c *Class, b *buf) {
	cls := c.Name
	n := (len(c.Virtuals) + 63) / 64
	if n == 0 {
		n = 1
	}
	b.p("class goqt_%s : public %s {\npublic:", cls, cls)
	b.p("\tusing %s::%s;", cls, cls)
	b.p("\tuintptr_t goqt_id = 0;\n\tuint64_t goqt_mask[%d] = {};", n)
	b.p("\tbool goqt_has(int i) const { return goqt_id && ((goqt_mask[i / 64] >> (i %% 64)) & 1); }")
	if c.Kind != KindObject {
		b.p("\t~goqt_%s() override { goqt_%s_dead(static_cast<void *>(static_cast<%s *>(this))); }", cls, c.Module.Pkg, cls)
	}
	protNames := map[string]bool{}
	for _, v := range c.Protected {
		if !protNames[v.IR.Name] {
			protNames[v.IR.Name] = true
			b.p("\tusing %s::%s;", v.Owner.Name, v.IR.Name)
		}
	}
	for _, v := range c.Virtuals {
		var decl, names []string
		for _, p := range v.Params {
			decl = append(decl, fmt.Sprintf("%s %s", v.IR.Params[indexOf(v, p)].Type.Canonical, p.CName))
			names = append(names, p.CName)
		}
		cst := ""
		if v.IR.Const {
			cst = " const"
		}
		rt := v.IR.Return.Canonical
		b.p("\t%s %s(%s)%s override {", rt, v.IR.Name, strings.Join(decl, ", "), cst)
		b.p("\t\tif (goqt_has(%d)) {", v.VIndex)
		var refs []string
		for i, p := range v.Params {
			b.p("\t\t\t%s c%d = %s;", cType(p.T), i, g.cppRet(p.T, p.CName))
			refs = append(refs, fmt.Sprintf("&c%d", i))
		}
		args := "nullptr"
		if len(refs) > 0 {
			b.p("\t\t\tvoid *args[] = {%s};", strings.Join(refs, ", "))
			args = "args"
		}
		if v.Ret.k == kVoid {
			b.p("\t\t\tgoqt_%s_virtual(goqt_id, %d, %s, nullptr);\n\t\t\treturn;", c.Module.Pkg, v.VIndex, args)
		} else {
			init := "{}"
			if v.Ret.k == kValue || v.Ret.k == kObj {
				init = " = nullptr"
			}
			if init == "{}" {
				b.p("\t\t\t%s r{};", cType(v.Ret))
			} else {
				b.p("\t\t\t%s r%s;", cType(v.Ret), init)
			}
			b.p("\t\t\tgoqt_%s_virtual(goqt_id, %d, %s, &r);", c.Module.Pkg, v.VIndex, args)
			b.p("\t\t\treturn %s;", g.cppVirtRet(v.Ret, "r"))
		}
		b.p("\t\t}")
		if v.IR.Pure {
			if v.Ret.k == kVoid {
				b.p("\t\treturn;")
			} else {
				b.p("\t\treturn %s();", strings.TrimSuffix(strings.TrimPrefix(v.IR.Return.Canonical, "const "), " &"))
			}
		} else {
			call := fmt.Sprintf("%s::%s(%s)", v.Owner.Name, v.IR.Name, strings.Join(names, ", "))
			if v.Ret.k == kVoid {
				b.p("\t\t%s;", call)
			} else {
				b.p("\t\treturn %s;", call)
			}
		}
		b.p("\t}")
		if !v.IR.Pure {
			b.p("\t%s goqt_super_%d(%s)%s { return %s::%s(%s); }", rt, v.VIndex, strings.Join(decl, ", "), cst, v.Owner.Name, v.IR.Name, strings.Join(names, ", "))
		}
	}
	b.p("};\n")
}

func indexOf(m *Method, p *Param) int {
	for i, q := range m.Params {
		if q == p {
			return i
		}
	}
	return -1
}

