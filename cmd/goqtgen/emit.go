func (g *Gen) cDecl(ret string, name string, params []string) string {
	if len(params) == 0 {
		params = []string{"void"}
	}
	return fmt.Sprintf("%s %s(%s)", ret, name, strings.Join(params, ", "))
}

func methodCParams(mm *Method, self bool) []string {
	var ps []string
	if self {
		ps = append(ps, "void *self")
	}
	for _, p := range mm.Params {
		ps = append(ps, cParams(p.T, p.CName)...)
	}
	return ps
}

func retCType(mm *Method) string {
	if mm.Ret == nil || mm.Ret.k == kVoid {
		return "void"
	}
	return cType(mm.Ret)
}

type cFunc struct {
	decl string
	body string
}

func (g *Gen) classCFuncs(c *Class) []cFunc {
	var out []cFunc
	add := func(decl, body string) { out = append(out, cFunc{decl, body}) }
	cls := c.Name
	self := fmt.Sprintf("static_cast<%s *>(self)", cls)
	if c.Shim {
		self = fmt.Sprintf("static_cast<%s *>(self)", cls)
	}
	ctorClass := cls
	if c.Shim && c.Kind != KindObject {
		ctorClass = "goqt_" + cls // notify-dtor shims always construct the shim
	}
	for _, mm := range c.Ctors {
		var args []string
		for _, p := range mm.Params {
			args = append(args, g.cppArg(p.T, p.CName))
		}
		add(g.cDecl("void *", mm.CName, methodCParams(mm, false)),
			fmt.Sprintf("return static_cast<%s *>(new %s(%s));", cls, ctorClass, strings.Join(args, ", ")))
	}
	if c.Opts.Subclass && c.Shim {
		if pc := primaryCtor(c); pc != nil {
			var args []string
			for _, p := range pc.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			add(g.cDecl("void *", "goqt_"+cls+"_new_shim", methodCParams(pc, false)),
				fmt.Sprintf("return static_cast<%s *>(new goqt_%s(%s));", cls, cls, strings.Join(args, ", ")))
		}
		add(g.cDecl("void", "goqt_"+cls+"_shim_init", []string{"void *self", "uintptr_t id", "const uint64_t *mask"}),
			fmt.Sprintf("auto s = static_cast<goqt_%s *>(static_cast<%s *>(self)); s->goqt_id = id; std::memcpy(s->goqt_mask, mask, sizeof(s->goqt_mask));", cls, cls))
		for _, v := range c.Virtuals {
			if v.IR.Pure {
				continue
			}
			var args []string
			for _, p := range v.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			call := fmt.Sprintf("static_cast<goqt_%s *>(static_cast<%s *>(self))->goqt_super_%d(%s)", cls, cls, v.VIndex, strings.Join(args, ", "))
			body := call + ";"
			if v.Ret.k != kVoid {
				body = "return " + g.cppRet(v.Ret, call) + ";"
			}
			add(g.cDecl(cType(v.Ret), v.CName, methodCParams(v, true)), body)
		}
		for _, v := range c.Protected {
			var args []string
			for _, p := range v.Params {
				args = append(args, g.cppArg(p.T, p.CName))
			}
			call := fmt.Sprintf("static_cast<goqt_%s *>(static_cast<%s *>(self))->%s(%s)", cls, cls, v.IR.Name, strings.Join(args, ", "))
			body := call + ";"
			if v.Ret.k != kVoid {
				body = "return " + g.cppRet(v.Ret, call) + ";"
			}
			add(g.cDecl(retCType(v), v.CName, methodCParams(v, true)), body)
		}
	}
	if c.Kind != KindObject && c.HasDtor && (c.IR.Dtor == nil || c.IR.Dtor.Access == "public") {
		add(g.cDecl("void", "goqt_"+cls+"_delete", []string{"void *self"}), fmt.Sprintf("delete %s;", self))
	}
	if c.QObject {
		add(g.cDecl("void *", "goqt_"+cls+"_cast", []string{"void *obj"}),
			fmt.Sprintf("return static_cast<void *>(qobject_cast<%s *>(static_cast<QObject *>(obj)));", cls))
	}
	for _, s := range c.Secondary {
		add(g.cDecl("void *", fmt.Sprintf("goqt_%s_as_%s", cls, s.Name), []string{"void *self"}),
			fmt.Sprintf("return static_cast<void *>(static_cast<%s *>(%s));", s.Name, self))
	}
	for _, mm := range append(append([]*Method{}, c.Methods...), c.Statics...) {
		var args []string
		for _, p := range mm.Params {
			args = append(args, g.cppArg(p.T, p.CName))
		}
		var call string
		if mm.IR.Static {
			call = fmt.Sprintf("%s::%s(%s)", cls, mm.IR.Name, strings.Join(args, ", "))
		} else {
			call = fmt.Sprintf("%s->%s(%s)", self, mm.IR.Name, strings.Join(args, ", "))
		}
		body := call + ";"
		if mm.Ret.k != kVoid {
			body = "return " + g.cppRet(mm.Ret, call) + ";"
		}
		add(g.cDecl(retCType(mm), mm.CName, methodCParams(mm, !mm.IR.Static)), body)
	}
	for _, sg := range c.Signals {
		out = append(out, g.signalCFunc(c, sg))
	}
	return out
}

func primaryCtor(c *Class) *Method {
	for _, m := range c.Ctors {
		if m.GoName == "New"+c.Name {
			return m
		}
	}
	if len(c.Ctors) > 0 {
		return c.Ctors[0]
	}
	for _, m := range c.ShimCtors {
		if len(m.Params) == 1 && m.Params[0].Rule == "transfer-this" {
			return m
		}
	}
	if len(c.ShimCtors) > 0 {
		return c.ShimCtors[0]
	}
	return nil
}

func (g *Gen) signalCFunc(c *Class, sg *Method) cFunc {
	cls := c.Name
	overloaded := 0
	for i := range c.IR.Methods {
		if c.IR.Methods[i].Kind == "signal" && c.IR.Methods[i].Name == sg.IR.Name {
			overloaded++
		}
	}
	ptr := fmt.Sprintf("&%s::%s", cls, sg.IR.Name)
	if overloaded > 1 {
		var ts []string
		for _, p := range sg.IR.Params {
			ts = append(ts, p.Type.Canonical)
		}
		ptr = fmt.Sprintf("static_cast<void (%s::*)(%s)>(%s)", cls, strings.Join(ts, ", "), ptr)
	}
	var lparams, conv, refs []string
	for i, p := range sg.Params {
		lparams = append(lparams, fmt.Sprintf("%s %s", p.T.cpp, p.CName))
		conv = append(conv, fmt.Sprintf("%s c%d = %s;", cType(p.T), i, g.cppRet(p.T, p.CName)))
		refs = append(refs, fmt.Sprintf("&c%d", i))
	}
	args := "nullptr"
	argDecl := ""
	if len(refs) > 0 {
		argDecl = fmt.Sprintf(" void *args[] = {%s};", strings.Join(refs, ", "))
		args = "args"
	}
	body := fmt.Sprintf("auto s = std::make_shared<GoSlot>(id);\n\tauto obj = static_cast<%s *>(self);\n"+
		"\treturn new QMetaObject::Connection(QObject::connect(obj, %s, obj, [s](%s) {%s%s goqt_%s_signal(s->id, %s); }));",
		cls, ptr, strings.Join(lparams, ", "), " "+strings.Join(conv, " "), argDecl, c.Module.Pkg, args)
	return cFunc{decl: g.cDecl("void *", sg.CName, []string{"void *self", "uintptr_t id"}), body: body}
}

func (g *Gen) emitHeader(m *Module, b *buf) {
	guard := "GOQT_" + strings.ToUpper(m.Pkg) + "_GEN_H"
	b.p("%s", strings.TrimSuffix(strings.ReplaceAll(genHeader, "//", "//"), "\n"))
	b.p("#ifndef %s\n#define %s\n", guard, guard)
	b.p("#include \"goqt_common.h\"\n")
	b.p("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
	b.p("const char *goqt_%s_check_layout(void);", m.Pkg)
	for _, c := range m.Classes {
		b.p("\n// %s", c.Name)
		for _, f := range g.classCFuncs(c) {
			b.p("%s;", f.decl)
		}
	}
	b.p("\n#ifdef __cplusplus\n}\n#endif\n\n#endif")
}

