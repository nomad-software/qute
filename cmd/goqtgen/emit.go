func kindConst(c *Class) string {
	switch {
	case c.Kind == KindValue:
		return "rt.KindValue"
	case c.QObject:
		return "rt.KindQObject"
	case c.Shim:
		return "rt.KindNotify"
	}
	return "rt.KindPlain"
}

func (g *Gen) deleterExpr(c *Class) string {
	if c.QObject {
		return "rt.DeleteQObject"
	}
	if c.HasDtor {
		return fmt.Sprintf("func(p unsafe.Pointer) { C.goqt_%s_delete(p) }", c.Name)
	}
	return "nil"
}

func (g *Gen) emitClass(c *Class) []byte {
	m := c.Module
	m.imports = map[string]bool{}
	var b buf
	cls := c.Name
	core := g.byName["QtCore"]

	// type
	kindDoc := map[ClassKind]string{
		KindObject: "It is a QObject: Go tracks its ownership and learns when Qt destroys it.",
		KindPlain:  "",
		KindValue:  "It is a Qt value class: each Go handle owns its own copy, freed by GC or Delete().",
	}[c.Kind]
	b.p("// %s wraps Qt's %s.", cls, cls)
	if kindDoc != "" {
		b.p("// %s", kindDoc)
	}
	if c.Event {
		b.p("// Event arguments are valid only inside the handler that receives them.")
	}
	b.p("//\n// Qt docs: %s", docURL(c, ""))
	if c.Base == nil {
		b.p("type %s struct{ goqtRef rt.Ref }\n", cls)
	} else {
		b.p("type %s struct{ %s }\n", cls, g.qual(c.Base.Module, m, c.Base.Name))
	}
	b.p("// %sLike is implemented by *%s and every type that embeds it.", cls, cls)
	b.p("type %sLike interface{ As%s() *%s }\n", cls, cls, cls)
	b.p("// As%s returns the receiver; it lets derived types be passed as %sLike.", cls, cls)
	b.p("func (this *%s) As%s() *%s { return this }\n", cls, cls, cls)
	b.p("func init() { rt.RegisterClass(%q, %s, %s) }\n", cls, kindConst(c), g.deleterExpr(c))
	own := g.qual(core, m, "Ownership")
	b.p("// %sFromPtr wraps an existing C++ %s. This is an unsafe escape hatch: own says", cls, cls)
	b.p("// who frees the object (Borrowed keeps the state of an already wrapped object).")
	b.p("func %sFromPtr(p unsafe.Pointer, own %s) *%s {", cls, own, cls)
	b.p("\treturn rt.View[%s](rt.WrapClass(p, %q, rt.ModeFor(own)), p)\n}\n", cls, cls)
	if c.QObject {
		ol := g.qual(core, m, "QObjectLike")
		b.p("// %sCast returns o as a *%s if it is one (qobject_cast), or nil.", cls, cls)
		b.p("func %sCast(o %s) *%s {", cls, ol, cls)
		b.p("\tif o == nil {\n\t\treturn nil\n\t}")
		b.p("\tself := rt.UseArg(unsafe.Pointer(o.AsQObject()), %q)", cls+"Cast")
		b.p("\tif self == nil {\n\t\treturn nil\n\t}")
		b.p("\tp := C.goqt_%s_cast(self)\n\tif p == nil {\n\t\treturn nil\n\t}", cls)
		b.p("\treturn rt.View[%s](rt.WrapClass(p, %q, rt.KeepOrBorrow), p)\n}\n", cls, cls)
	}
	if c.Base == nil {
		g.emitRootMethods(c, &b)
	}
	for _, s := range c.Secondary {
		st := g.qual(s.Module, m, s.Name)
		b.p("// As%s returns the %s part of this object, sharing its ownership state.", s.Name, s.Name)
		b.p("func (this *%s) As%s() *%s {", cls, s.Name, st)
		b.p("\tself := rt.Use(unsafe.Pointer(this), %q)", cls+".As"+s.Name)
		b.p("\tp := C.goqt_%s_as_%s(self)", cls, s.Name)
		b.p("\treturn rt.View[%s](rt.RefOf(unsafe.Pointer(this)).H, p)\n}\n", st)
	}
	for _, mm := range c.Ctors {
		g.emitCtor(c, mm, &b)
	}
	for _, mm := range c.Methods {
		g.emitMethod(c, mm, &b, false)
	}
	for _, mm := range c.Statics {
		g.emitMethod(c, mm, &b, true)
	}
	for _, sg := range c.Signals {
		g.emitSignal(c, sg, &b)
	}
	if c.Opts.Subclass && c.Shim {
		g.emitSubclass(c, &b)
	}
	var out buf
	g.preamble(m, &out)
	std := []string{"unsafe"}
	if bytes.Contains(b.Bytes(), []byte("fmt.")) {
		std = append([]string{"fmt"}, std...)
	}
	g.importBlock(m, &out, std)
	out.Write(b.Bytes())
	return out.Bytes()
}

func (g *Gen) emitRootMethods(c *Class, b *buf) {
	cls := c.Name
	own := g.qual(g.byName["QtCore"], c.Module, "Ownership")
	b.p("// Ptr returns the C++ pointer (unsafe escape hatch). It is nil for a nil receiver.")
	b.p("func (this *%s) Ptr() unsafe.Pointer {\n\tif this == nil {\n\t\treturn nil\n\t}\n\treturn this.goqtRef.P\n}\n", cls)
	b.p("// Alive reports whether the C++ object still exists.")
	b.p("func (this *%s) Alive() bool { return this != nil && this.goqtRef.H.Alive() }\n", cls)
	b.p("// Ownership reports who frees the object: Owned, Parented, Borrowed or Dead.")
	b.p("func (this *%s) Ownership() %s {\n\tif this == nil {\n\t\treturn rt.Dead\n\t}\n\treturn this.goqtRef.H.State()\n}\n", cls, own)
	b.p("// Delete destroys the C++ object now. It is idempotent and works on Owned and")
	b.p("// Parented objects; on Borrowed objects it panics. Inside a signal or event")
	b.p("// handler use DeleteLater() instead.")
	b.p("func (this *%s) Delete() {\n\tif this == nil {\n\t\treturn\n\t}\n\trt.CheckThread(%q)\n\tthis.goqtRef.H.Delete(%q)\n}\n", cls, cls+".Delete", rt0(c)+".Delete")
	b.p("// Keep pins the object so GC never frees it, until Unkeep.")
	b.p("func (this *%s) Keep() {\n\tif this != nil {\n\t\tthis.goqtRef.H.Keep()\n\t}\n}\n", cls)
	b.p("// Unkeep releases one Keep.")
	b.p("func (this *%s) Unkeep() {\n\tif this != nil {\n\t\tthis.goqtRef.H.Unkeep()\n\t}\n}\n", cls)
}

func rt0(c *Class) string { return c.Name }

func (g *Gen) docLines(c *Class, mm *Method, b *buf, what string) {
	b.p("// %s wraps %s.", mm.GoName, what)
	b.p("//\n//\tC++: %s", mm.Sig)
	var rules []string
	for _, p := range mm.Params {
		if p.Rule == "" || p.Rule == "borrowed" && !p.Ruled {
			continue
		}
		desc := map[string]string{
			"transfer-to-cpp": "becomes Parented: Qt frees it from now on",
			"transfer-to-go":  "becomes Owned: Go frees it from now on",
			"transfer-this":   "the receiver becomes Parented when it is non-nil, Owned when nil",
			"borrowed":        "is borrowed for the call only",
			"scoped":          "is valid only during the call",
		}[p.Rule]
		rules = append(rules, fmt.Sprintf("%s %s", p.GoName, desc))
	}
	switch mm.RetRule {
	case "transfer-to-go", "owned":
		rules = append(rules, "the result is Owned: Go frees it")
	case "parented":
		rules = append(rules, "the result is Parented: its Qt parent frees it")
	case "borrowed":
		rules = append(rules, "the result is Borrowed: Go never frees it")
	}
	if mm.Ret != nil && mm.Ret.k == kValue {
		rules = append(rules, "the result is an Owned copy")
	}
	if len(rules) > 0 {
		b.p("//\n// Ownership: %s.", strings.Join(rules, "; "))
	}
	if mm.Overlay != nil && mm.Overlay.Doc != "" {
		b.p("//\n// %s", mm.Overlay.Doc)
	}
	anchor := mm.IR.Name
	if mm.IR.Kind == "ctor" {
		anchor = mm.Class.Name
	}
	b.p("//\n// Qt docs: %s", docURL(mm.Owner, anchor))
}

type goCall struct {
	params []string
	pre    []string
	args   []string
	post   []string
}

func (g *Gen) prepCall(c *Class, mm *Method, method string, virtualParams bool) goCall {
	var gc goCall
	m := c.Module
	for _, p := range mm.Params {
		gt := g.goType(p.T, m, !virtualParams)
		if p.T.k == kObj && virtualParams {
			gt = "*" + g.qual(p.T.cls.Module, m, p.T.cls.Name)
		}
		gc.params = append(gc.params, p.GoName+" "+gt)
		if p.T.k == kObj {
			pp, hh := p.GoName+"Ptr", p.GoName+"H"
			gc.pre = append(gc.pre, fmt.Sprintf("var %s unsafe.Pointer", pp))
			needH := p.Rule == "transfer-to-cpp" || p.Rule == "transfer-to-go"
			if needH {
				gc.pre = append(gc.pre, fmt.Sprintf("var %s *rt.Handle", hh))
				gc.pre = append(gc.pre, fmt.Sprintf("if %s != nil {\n\t\t%s, %s = rt.Arg(unsafe.Pointer(%s.As%s()), %q)\n\t}", p.GoName, pp, hh, p.GoName, p.T.cls.Name, method))
			} else {
				gc.pre = append(gc.pre, fmt.Sprintf("if %s != nil {\n\t\t%s = rt.UseArg(unsafe.Pointer(%s.As%s()), %q)\n\t}", p.GoName, pp, p.GoName, p.T.cls.Name, method))
			}
			gc.args = append(gc.args, pp)
			switch p.Rule {
			case "transfer-to-cpp":
				gc.post = append(gc.post, fmt.Sprintf("%s.TransferToCpp()", hh))
			case "transfer-to-go":
				gc.post = append(gc.post, fmt.Sprintf("%s.TransferToGo()", hh))
			case "transfer-this":
				if mm.IR.Kind != "ctor" {
					gc.post = append(gc.post, fmt.Sprintf("rt.RefOf(unsafe.Pointer(this)).H.SetParented(%s != nil)", pp))
				}
			}
			continue
		}
		pre, args := g.goArg(p.T, p.GoName, method, m)
		gc.pre = append(gc.pre, pre...)
		gc.args = append(gc.args, args...)
		if p.T.k == kList && p.T.elem.k == kObj && p.Rule == "transfer-to-cpp" {
			gc.post = append(gc.post, fmt.Sprintf("for _, x := range %s {\n\t\tif x != nil {\n\t\t\trt.RefOf(unsafe.Pointer(x)).H.TransferToCpp()\n\t\t}\n\t}", p.GoName))
		}
	}
	return gc
}

func retMode(mm *Method) string {
	switch mm.RetRule {
	case "transfer-to-go", "owned":
		return "rt.TakeOwned"
	case "parented":
		return "rt.TakeParented"
	}
	return "rt.KeepOrBorrow"
}

func (g *Gen) emitCtor(c *Class, mm *Method, b *buf) {
	method := mm.GoName
	gc := g.prepCall(c, mm, method, false)
	g.docLines(c, mm, b, fmt.Sprintf("the %s constructor", c.Name))
	b.p("func %s(%s) *%s {", mm.GoName, strings.Join(gc.params, ", "), c.Name)
	b.p("\trt.CheckThread(%q)", method)
	for _, s := range gc.pre {
		b.p("\t%s", s)
	}
	b.p("\tp := C.%s(%s)", mm.CName, strings.Join(gc.args, ", "))
	mode := "rt.NewOwned"
	var parentPtr string
	for _, p := range mm.Params {
		if p.Rule == "transfer-this" && p.T.k == kObj {
			parentPtr = p.GoName + "Ptr"
		}
	}
	if parentPtr != "" && c.Kind != KindValue {
		b.p("\tmode := rt.NewOwned\n\tif %s != nil {\n\t\tmode = rt.NewParented\n\t}", parentPtr)
		mode = "mode"
	}
	b.p("\th := rt.WrapClass(p, %q, %s)", c.Name, mode)
	for _, s := range gc.post {
		b.p("\t%s", s)
	}
	b.p("\treturn rt.View[%s](h, p)\n}\n", c.Name)
}

func (g *Gen) emitMethod(c *Class, mm *Method, b *buf, static bool) {
	m := c.Module
	method := c.Name + "." + mm.GoName
	if static {
		method = mm.GoName
	}
	gc := g.prepCall(c, mm, method, false)
	ret := g.goType(mm.Ret, m, false)
	if mm.Error {
		ret = "error"
	}
	if mm.Emit {
		g.docLines(c, mm, b, "emitting the "+mm.IR.Name+" signal")
	} else {
		g.docLines(c, mm, b, c.Name+"::"+mm.IR.Name)
	}
	recv := ""
	if !static {
		recv = fmt.Sprintf("(this *%s) ", c.Name)
	}
	b.p("func %s%s(%s) %s {", recv, mm.GoName, strings.Join(gc.params, ", "), ret)
	args := gc.args
	if static {
		b.p("\trt.CheckThread(%q)", method)
	} else {
		b.p("\tself := rt.Use(unsafe.Pointer(this), %q)", method)
		args = append([]string{"self"}, args...)
	}
	for _, s := range gc.pre {
		b.p("\t%s", s)
	}
	call := fmt.Sprintf("C.%s(%s)", mm.CName, strings.Join(args, ", "))
	if mm.Ret.k == kVoid {
		b.p("\t%s", call)
		for _, s := range gc.post {
			b.p("\t%s", s)
		}
		b.p("}\n")
		return
	}
	b.p("\tr := %s", call)
	for _, s := range gc.post {
		b.p("\t%s", s)
	}
	if mm.Error {
		msg := fmt.Sprintf("fmt.Errorf(\"%s: failed\")", method)
		if mm.Overlay.ErrorMsg != "" {
			msg = fmt.Sprintf("fmt.Errorf(\"%s: %%s\", this.%s())", method, mm.Overlay.ErrorMsg)
		}
		b.p("\tif !bool(r) {\n\t\treturn %s\n\t}\n\treturn nil\n}\n", msg)
		return
	}
	b.p("\treturn %s\n}\n", g.goRet(mm.Ret, "r", retMode(mm), m))
}

// unpackArgs converts a shim argument array into Go values. Scoped object
// arguments get handles that expire when the callback returns.
func (g *Gen) unpackArgs(c *Class, mm *Method, b *buf, indent string) []string {
	m := c.Module
	var names []string
	if len(mm.Params) == 0 {
		return nil
	}
	b.p("%sa := unsafe.Slice((*unsafe.Pointer)(args), %d)", indent, len(mm.Params))
	for i, p := range mm.Params {
		cv := fmt.Sprintf("*(*%s)(a[%d])", g.cgoType(p.T), i)
		if p.T.k == kObj && p.Rule == "scoped" {
			hn := p.GoName + "H"
			cls := g.qual(p.T.cls.Module, m, p.T.cls.Name)
			b.p("%s%sP := %s", indent, p.GoName, cv)
			b.p("%s%s := rt.WrapClass(%sP, %q, rt.NewScoped)", indent, hn, p.GoName, p.T.cls.Name)
			b.p("%sdefer %s.Expire()", indent, hn)
			b.p("%s%s := rt.View[%s](%s, %sP)", indent, p.GoName, cls, hn, p.GoName)
		} else {
			b.p("%s%s := %s", indent, p.GoName, g.goRet(p.T, cv, "rt.KeepOrBorrow", m))
		}
		names = append(names, p.GoName)
	}
	return names
}

func (g *Gen) emitSignal(c *Class, sg *Method, b *buf) {
	m := c.Module
	method := c.Name + "." + sg.GoName
	var ps []string
	for _, p := range sg.Params {
		ps = append(ps, p.GoName+" "+g.goType(p.T, m, false))
	}
	conn := g.qual(g.byName["QtCore"], m, "Connection")
	b.p("// %s connects f to the %s signal. The connection ends when the", sg.GoName, sg.IR.Name)
	b.p("// sender is destroyed or Disconnect is called; until then the sender is pinned.")
	b.p("//\n//\tC++: %s [signal]", sg.Sig)
	for _, p := range sg.Params {
		if p.Rule == "scoped" {
			b.p("//\n// %s is valid only inside f.", p.GoName)
		}
	}
	b.p("//\n// Qt docs: %s", docURL(c, sg.IR.Name))
	b.p("func (this *%s) %s(f func(%s)) %s {", c.Name, sg.GoName, strings.Join(ps, ", "), conn)
	b.p("\tself := rt.Use(unsafe.Pointer(this), %q)", method)
	b.p("\tid := rt.NewCallback(rt.RefOf(unsafe.Pointer(this)).H, func(args unsafe.Pointer) {")
	names := g.unpackArgs(c, sg, b, "\t\t")
	if len(sg.Params) == 0 {
		b.p("\t\t_ = args")
	}
	b.p("\t\tf(%s)", strings.Join(names, ", "))
	b.p("\t})")
	b.p("\treturn rt.NewConnection(C.%s(self, C.uintptr_t(id)))\n}\n", sg.CName)
}

func (g *Gen) virtualSig(c *Class, v *Method) string {
	m := c.Module
	var ps []string
	for _, p := range v.Params {
		ps = append(ps, g.goType(p.T, m, false))
	}
	r := g.goType(v.Ret, m, false)
	return fmt.Sprintf("%s(%s) %s", v.GoName, strings.Join(ps, ", "), r)
}

func (g *Gen) emitSubclass(c *Class, b *buf) {
	m := c.Module
	cls := c.Name
	lower := "goqt" + cls
	vt := strings.ToLower(cls[:1]) + cls[1:] + "VTable"
	pc := primaryCtor(c)
	if pc == nil {
		return
	}
	// dispatch table
	b.p("var %s = []rt.Virtual{", vt)
	for _, v := range c.Virtuals {
		iface := fmt.Sprintf("interface{ %s }", g.virtualSig(c, v))
		b.p("\t{Name: %q, Has: func(v any) bool { _, ok := v.(%s); return ok },", v.GoName, iface)
		b.p("\t\tCall: func(v any, args, ret unsafe.Pointer) {")
		names := g.unpackArgs(c, v, b, "\t\t\t")
		call := fmt.Sprintf("v.(%s).%s(%s)", iface, v.GoName, strings.Join(names, ", "))
		if v.Ret.k == kVoid {
			if len(v.Params) == 0 {
				b.p("\t\t\t_ = args")
			}
			b.p("\t\t\t%s", call)
		} else {
			if len(v.Params) == 0 {
				b.p("\t\t\t_ = args")
			}
			b.p("\t\t\tr := %s", call)
			ex, _ := g.goVirtRet(v.Ret, "r", cls+"."+v.GoName, m)
			b.p("\t\t\t*(*%s)(ret) = %s", g.cgoType(v.Ret), ex)
		}
		b.p("\t\t}},")
	}
	b.p("}\n")

	b.p("// %sBase is embedded in Go types that subclass %s:", cls, cls)
	b.p("//\n//\ttype My%s struct{ %s.%sBase }", strings.TrimPrefix(cls, "Q"), m.Pkg, cls)
	b.p("//\n// Define any of the virtual methods listed on %sSuper to override them,", cls)
	b.p("// then construct the value with New%sWith. Call b.Super().X() for the", cls)
	b.p("// base implementation.")
	b.p("type %sBase struct{ *%s }\n", cls, cls)
	b.p("func (b *%sBase) %sBase() *%sBase { return b }\n", cls, lower, cls)
	b.p("// %sSubclass is implemented by every type that embeds %sBase.", cls, cls)
	b.p("type %sSubclass interface{ %sBase() *%sBase }\n", cls, lower, cls)
	b.p("// Super returns the C++ base implementations of %s's virtual methods.", cls)
	b.p("func (b *%sBase) Super() *%sSuper { return &%sSuper{this: b.%s} }\n", cls, cls, cls, cls)
	b.p("// %sSuper calls the C++ base implementations of %s's virtuals.", cls, cls)
	b.p("type %sSuper struct{ this *%s }\n", cls, cls)
	for _, v := range c.Virtuals {
		if v.IR.Pure {
			continue
		}
		gc := g.prepCall(c, v, cls+".Super."+v.GoName, true)
		r := g.goType(v.Ret, m, false)
		b.p("// %s calls %s::%s.", v.GoName, v.Owner.Name, v.IR.Name)
		b.p("func (s *%sSuper) %s(%s) %s {", cls, v.GoName, strings.Join(gc.params, ", "), r)
		b.p("\tself := rt.Use(unsafe.Pointer(s.this), %q)", cls+".Super."+v.GoName)
		for _, x := range gc.pre {
			b.p("\t%s", x)
		}
		call := fmt.Sprintf("C.%s(%s)", v.CName, strings.Join(append([]string{"self"}, gc.args...), ", "))
		if v.Ret.k == kVoid {
			b.p("\t%s\n}\n", call)
		} else {
			b.p("\treturn %s\n}\n", g.goRet(v.Ret, call, "rt.KeepOrBorrow", m))
		}
	}
	for _, v := range c.Protected {
		gc := g.prepCall(c, v, cls+"."+v.GoName, false)
		r := g.goType(v.Ret, m, false)
		b.p("// %s wraps the protected %s::%s for subclasses.", v.GoName, v.Owner.Name, v.IR.Name)
		b.p("func (b *%sBase) %s(%s) %s {", cls, v.GoName, strings.Join(gc.params, ", "), r)
		b.p("\tself := rt.Use(unsafe.Pointer(b.%s), %q)", cls, cls+"."+v.GoName)
		for _, x := range gc.pre {
			b.p("\t%s", x)
		}
		call := fmt.Sprintf("C.%s(%s)", v.CName, strings.Join(append([]string{"self"}, gc.args...), ", "))
		if v.Ret.k == kVoid {
			b.p("\t%s", call)
			for _, x := range gc.post {
				b.p("\t%s", x)
			}
			b.p("}\n")
		} else {
			b.p("\tr := %s", call)
			for _, x := range gc.post {
				b.p("\t%s", x)
			}
			b.p("\treturn %s\n}\n", g.goRet(v.Ret, "r", retMode(v), m))
		}
	}
	// constructor
	gc := g.prepCall(c, pc, "New"+cls+"With", false)
	b.p("// New%sWith constructs a %s whose virtual methods dispatch to v. The", cls, cls)
	b.p("// object stays pinned while it lives, so v's Go state survives even when only")
	b.p("// Qt references it.")
	b.p("func New%sWith(%s) *%s {", cls, strings.Join(append([]string{"v " + cls + "Subclass"}, gc.params...), ", "), cls)
	b.p("\trt.CheckThread(%q)", "New"+cls+"With")
	b.p("\tbase := v.%sBase()", lower)
	b.p("\tif base.%s != nil {\n\t\tpanic(%q)\n\t}", cls, "New"+cls+"With: value is already constructed; use a fresh value")
	for _, s := range gc.pre {
		b.p("\t%s", s)
	}
	b.p("\tp := C.goqt_%s_new_shim(%s)", cls, strings.Join(gc.args, ", "))
	mode := "rt.NewOwned"
	for _, p := range pc.Params {
		if p.Rule == "transfer-this" && p.T.k == kObj {
			b.p("\tmode := rt.NewOwned\n\tif %sPtr != nil {\n\t\tmode = rt.NewParented\n\t}", p.GoName)
			mode = "mode"
		}
	}
	b.p("\th := rt.WrapClass(p, %q, %s)", cls, mode)
	for _, s := range gc.post {
		b.p("\t%s", s)
	}
	b.p("\tbase.%s = rt.View[%s](h, p)", cls, cls)
	b.p("\tid := h.SetSelf(v, %s)", vt)
	b.p("\tmask := rt.Mask(v, %s)", vt)
	b.p("\tif len(mask) == 0 {\n\t\tmask = []uint64{0}\n\t}")
	b.p("\tC.goqt_%s_shim_init(p, C.uintptr_t(id), (*C.uint64_t)(unsafe.Pointer(&mask[0])))", cls)
	b.p("\treturn base.%s\n}\n", cls)
}
