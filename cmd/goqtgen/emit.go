const genHeader = "// Code generated by goqtgen from spec/ and spec/ir/. DO NOT EDIT.\n"

type buf struct{ bytes.Buffer }

func (b *buf) p(format string, a ...any) { fmt.Fprintf(&b.Buffer, format, a...); b.WriteByte('\n') }

func writeFile(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	return os.WriteFile(path, data, 0o644)
}

func writeGo(path string, src []byte) error {
	out, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(path+".broken", src, 0o644)
		return fmt.Errorf("%s: %w", path, err)
	}
	return writeFile(path, out)
}

func docURL(c *Class, method string) string {
	u := "https://doc.qt.io/qt-6/" + strings.ToLower(c.Name) + ".html"
	if method != "" {
		u += "#" + method
	}
	return u
}

func (g *Gen) emitModule(m *Module) error {
	dir := filepath.Join(g.root, m.Pkg)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// remove stale generated files
	old, _ := filepath.Glob(filepath.Join(dir, "*_gen.go"))
	keep := map[string]bool{}
	if err := writeFile(filepath.Join(dir, "goqt_common.h"), []byte(commonHeader)); err != nil {
		return err
	}
	var h, cpp buf
	g.emitHeader(m, &h)
	if err := writeFile(filepath.Join(dir, m.Pkg+"_gen.h"), h.Bytes()); err != nil {
		return err
	}
	g.emitCpp(m, &cpp)
	if err := writeFile(filepath.Join(dir, m.Pkg+"_gen.cpp"), cpp.Bytes()); err != nil {
		return err
	}
	files := map[string][]byte{}
	files["goqt_gen.go"] = g.emitHelpers(m)
	files["enums_gen.go"] = g.emitEnums(m)
	for _, c := range m.Classes {
		files[strings.ToLower(c.Name)+"_gen.go"] = g.emitClass(c)
	}
	for name, src := range files {
		p := filepath.Join(dir, name)
		keep[p] = true
		if err := writeGo(p, src); err != nil {
			return err
		}
	}
	for _, o := range old {
		if !keep[o] {
			os.Remove(o)
		}
	}
	return g.emitTests(m, dir)
}

